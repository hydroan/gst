// TestMigrateProgramLinksWhatMainLinks pins what the migration program links:
// its model set is whatever the linked packages registered, so it has to link
// the project packages every generated main.go links and the framework entry
// point that links the rest, and it has to initialize the router and modules
// through that entry point instead of guessing when module registration is
// done. A scaffold package the project lacks — restored by gg gen, never by
// migrate — is left out rather than failing the build, which is what a project
// that has not run gen yet looks like.
func TestMigrateProgramLinksWhatMainLinks(t *testing.T) {
	projectDir := t.TempDir()
	for _, dir := range ggconst.ProjectImportDirs {
		if dir == ggconst.DirLock {
			// Left missing on purpose.
			continue
		}
		if err := os.MkdirAll(filepath.Join(projectDir, dir), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(projectDir, dir, dir+".go"), []byte("package "+dir+"\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(projectDir)

	program, err := buildMigrateProgramForMode("sample", false, "", nil)
	if err != nil {
		t.Fatal(err)
	}

	// The project file is the example of buildMigrateProjectFile's doc
	// comment: the same input, with the lock package missing.
	if want := `// Code generated by gst; DO NOT EDIT.

package main

import (
	_ "sample/component"
	_ "sample/configx"
	_ "sample/cronjob"
	_ "sample/leader"
	_ "sample/middleware"
	_ "sample/model"
	_ "sample/module"
	_ "sample/router"
	_ "sample/service"
)
`; program.Files[migrateProjectFileName] != want {
		t.Fatalf("unexpected project file:\n%s\nwant:\n%s", program.Files[migrateProjectFileName], want)
	}
	main := program.Files["main.go"]
	for _, want := range []string{`"github.com/hydroan/gst/bootstrap"`, "bootstrap.InitRouterAndModules()"} {
		if !strings.Contains(main, want) {
			t.Fatalf("expected the migration program to contain %s, got:\n%s", want, main)
		}
	}
	for name, source := range program.Files {
		if _, err := parser.ParseFile(token.NewFileSet(), name, source, parser.AllErrors); err != nil {
			t.Fatalf("expected the migration program's %s to parse, got %v", name, err)
		}
	}
	// The mode travels as flags, so the sources stay the same between runs.
	if !slices.Equal(program.Args, []string{"-module", "sample", "-dry-run=false", "-yes=false", "-accept-data-loss=false", "-schema-only=false", "-schema-source", ""}) {
		t.Fatalf("unexpected migration program arguments: %q", program.Args)
	}
}

