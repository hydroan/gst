var migrateCmd = &cobra.Command{
	Use:   "migrate",
	Short: "Run database migrations",
	Long: `Generate and execute database migration code based on current models.

On SQLite the migration targets the database file sqlite.path names. An
in-memory database, which sqlite.is_memory selects by default, has nothing to
migrate: the application creates its tables from the models every time it
starts.`,
	RunE: func(cmd *cobra.Command, args []string) error {
		// 1. Get module name
		moduleName, err := gghelper.ModulePath(".")
		if err != nil {
			return errors.Wrap(err, "failed to get module path")
		}

		program, err := buildMigrateProgramForMode(moduleName, false, "", nil)
		if err != nil {
			return err
		}
		return runGeneratedMigrateProgram(program, "Migration", "Preparing migration...")
	},
}

var migrateSchemaCmd = &cobra.Command{
	Use:   "schema [path]",
	Short: "Print schema SQL for registered models",
	Long:  "Print target schema SQL for all registered models, or only registered models declared in a file or directory",
	Args:  cobra.MaximumNArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		moduleName, err := gghelper.ModulePath(".")
		if err != nil {
			return errors.Wrap(err, "failed to get module path")
		}

		source := ""
		if len(args) > 0 {
			source = strings.TrimSpace(args[0])
		}
		files, err := migrateSourceFiles(source, gghelper.NewProjectIgnore())
		if err != nil {
			return err
		}
		program, err := buildMigrateSchemaProgram(moduleName, source, files)
		if err != nil {
			return err
		}
		return runGeneratedMigrateProgram(program, "Migration Schema", "Preparing schema dump...")
	},
}

var (
	migrateDryRun bool
	migrateYes    bool
)

func init() {
	migrateCmd.Flags().BoolVar(&migrateDryRun, "dry-run", false, "Preview migration SQL without applying changes")
	migrateCmd.Flags().BoolVar(&migrateYes, "yes", false, "Apply migration without prompting for confirmation")
	migrateCmd.AddCommand(migrateSchemaCmd)
}

// migrateProjectFileName is the file generated for the project next to the
// embedded migration program (gghelper.MigrateProgram): the project packages
// it links, see migrateProjectImports.
const migrateProjectFileName = "project.go"

func buildMigrateSchemaProgram(moduleName string, source string, sourceFiles []string) (gghelper.ProjectProgram, error) {
	return buildMigrateProgramForMode(moduleName, true, source, sourceFiles)
}

// buildMigrateProgramForMode assembles the migration program for the project:
// the embedded sources, the generated project.go, and the flags that select
// the mode, so that the sources, and with them the build Go caches, stay the
// same between runs.
func buildMigrateProgramForMode(moduleName string, schemaOnly bool, schemaSource string, schemaSourceFiles []string) (gghelper.ProjectProgram, error) {
	files := gghelper.MigrateProgram()
	project, err := buildMigrateProjectFile(moduleName)
	if err != nil {
		return gghelper.ProjectProgram{}, err
	}
	files[migrateProjectFileName] = project
	args := []string{
		"-module", moduleName,
		"-dry-run=" + strconv.FormatBool(migrateDryRun),
		"-yes=" + strconv.FormatBool(migrateYes),
		"-schema-only=" + strconv.FormatBool(schemaOnly),
		"-schema-source", schemaSource,
	}
	for _, file := range schemaSourceFiles {
		args = append(args, "-schema-source-file", file)
	}
	return gghelper.ProjectProgram{Files: files, Args: args}, nil
}

// buildMigrateProjectFile generates the file that completes the embedded
// migration program for the project: one blank import per project package
// the program links, the same list a generated main.go imports, so the
// program registers every model the running service does; a package the
// project does not have is left out with a note (see migrateProjectImports).
// For the module sample whose lock package is missing it generates
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package main
//
//	import (
//		_ "sample/component"
//		_ "sample/configx"
//		_ "sample/cronjob"
//		_ "sample/leader"
//		_ "sample/middleware"
//		_ "sample/model"
//		_ "sample/module"
//		_ "sample/router"
//		_ "sample/service"
//	)
func buildMigrateProjectFile(moduleName string) (string, error) {
	paths := migrateProjectImports(moduleName)
	specs := make([]ast.Spec, 0, len(paths))
	for _, importPath := range paths {
		specs = append(specs, &ast.ImportSpec{
			Name: ast.NewIdent("_"),
			Path: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(importPath)},
		})
	}
	f := &ast.File{
		Name:  ast.NewIdent("main"),
		Decls: []ast.Decl{&ast.GenDecl{Tok: token.IMPORT, Specs: specs}},
	}
	fset := goast.GeneratedHeader(f)
	return gghelper.FormatNodeExtraWithFileSet(f, fset, moduleName)
}

// migrateProjectImports lists the project packages the migration program
// links, the same list a generated main.go imports, so the program registers
// every model the running service does.
//
// A package the project does not have yet — a scaffold gg gen has not
// written into the project — is left out, with a note: it registers nothing,
// and the service does not build without it either, so the migration must not
// fail on its account. Migration never writes source files; restoring the
// scaffold is gen's job.
func migrateProjectImports(moduleName string) []string {
	paths := make([]string, 0, len(ggconst.ProjectImportDirs))
	for _, dir := range ggconst.ProjectImportDirs {
		if !hasGoSources(dir) {
			clioutput.Warn("", "%s/ has no Go files and is left out of the migration program; run gg gen to restore the scaffold", dir)
			continue
		}
		paths = append(paths, moduleName+"/"+dir)
	}
	return paths
}

// hasGoSources reports whether dir holds a Go source file that is not a
// test: a directory of test files alone is no package to import.
func hasGoSources(dir string) bool {
	sources, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, source := range sources {
		if !strings.HasSuffix(source, "_test.go") {
			return true
		}
	}
	return false
}

// migrateSourceFiles lists the Go files gg migrate schema reads model types
// from: source itself when it names a Go file, or else the Go files below it
// that are not tests, leaving out what the go command leaves out
// (ignore.ExcludedByGo) but not what the project's Git ignore rules do, since
// the user named source. For model it lists model/record.go and
// model/sample/item.go, and leaves out model/record_test.go, model/_draft.go
// and every file of model/testdata. An empty source lists nothing: the schema
// covers every registered model.
func migrateSourceFiles(source string, ignore gghelper.ProjectIgnore) ([]string, error) {
	if source == "" {
		return nil, nil
	}
	isSource := func(path string) bool {
		return strings.HasSuffix(path, ggconst.ExtensionGo) && !strings.HasSuffix(path, ggconst.PatternTestFile)
	}
	info, err := os.Stat(source)
	if err != nil {
		return nil, errors.Wrapf(err, "failed to inspect model source %s", source)
	}
	if !info.IsDir() {
		if !isSource(source) {
			return nil, errors.Newf("model source must be a Go file or directory: %s", source)
		}
		return []string{source}, nil
	}

	var files []string
	err = filepath.WalkDir(source, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if path != source && ignore.ExcludedByGo(path, entry.IsDir()) {
			if entry.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if !entry.IsDir() && isSource(path) {
			files = append(files, path)
		}
		return nil
	})
	if err != nil {
		return nil, errors.Wrapf(err, "failed to walk model source %s", source)
	}
	if len(files) == 0 {
		return nil, errors.Newf("no Go model files found under %s", source)
	}
	sort.Strings(files)
	return files, nil
}

func runGeneratedMigrateProgram(program gghelper.ProjectProgram, section string, message string) error {
	clioutput.Section(section)
	clioutput.Info("", "%s", message)

	// Migration prints its own progress and prompts for confirmation, so its
	// output and input stay connected to the terminal.
	program.Stdout, program.Interactive = os.Stdout, true
	return program.Run()
}
