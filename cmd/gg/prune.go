// pruneCmd is gg prune; PRUNE.md next to this file lays out what it deletes,
// what it keeps and the order it goes in. It deletes from service/,
// middleware/, interceptor/ and pb/ alone.
var pruneCmd = &cobra.Command{
	Use:   "prune",
	Short: "Clean what the models no longer need from service/, middleware/, interceptor/ and pb/",
	Long: "Clean what the current models no longer need, asking once before deleting: the service files of disabled actions with their test files, " +
		"the unmanaged files of service directories no model owns, the middleware and interceptors of removed copied modules with their register calls, " +
		"the protobuf files, definitions and the Go files compiled from them, of models no longer served over gRPC, and the directories this leaves empty. " +
		"It touches service/, middleware/, interceptor/ and pb/ only, and gst.yaml's prune.ignore is the one way to keep a path there. " +
		"A file under pb/ named like the ones gg gen writes but not generated by gst stops it before anything is deleted; " +
		"a file it cannot delete fails it once it has deleted the rest.",
	Args: cobra.NoArgs,
	RunE: func(cmd *cobra.Command, args []string) error {
		return pruneRun()
	},
}

// pruneRun prunes the project in the working directory. The errors it
// returns stop it before it deletes anything: the module path or gst.yaml
// could not be read, the model directory is missing, a model file fails to
// parse, the protobuf definitions cannot be derived, or a file under pb/ it
// would delete was not generated by gst; but for a file it could not
// delete, which fails it once it has deleted the rest (see deleteLeftovers).
// It ends on what it removed, or on there being nothing to prune; a run
// whose question was answered with a no has said so already.
func pruneRun() error {
	started := time.Now()
	if len(module) == 0 {
		var err error
		module, err = gghelper.ModulePath(".")
		if err != nil {
			return err
		}
	}

	if !gghelper.FileExists(ggconst.DirModel) {
		return errors.Newf("model dir not found: %s", ggconst.DirModel)
	}

	projectCfg, err := loadProjectConfig()
	if err != nil {
		return err
	}

	// Scan all models the way gg gen does: which models the project declares
	// is gen's to say, and prune only works out what they leave behind.
	ignore := gghelper.NewProjectIgnore()
	allModels, err := modelinfo.FindModels(module, ggconst.DirModel, ignore)
	if err != nil {
		return err
	}

	// Route ignores from gst.yaml are intentionally not applied here: an
	// ignored action keeps its service file on disk, so leaving the action
	// enabled makes prune treat the file as expected without extra bookkeeping.

	// Scan the existing service files and the files under pb/
	serviceFiles := existingServiceFiles()
	pbFiles := existingPBFiles()
	generatedPBFiles, err := generatedPBFiles(ignore, projectCfg)
	if err != nil {
		return err
	}

	log := new(changes)
	declined, err := pruneLeftovers(log, serviceFiles, allModels, ignore, projectCfg.Prune, pbFiles, generatedPBFiles)
	if err != nil || declined {
		return err
	}
	if summary := log.summary(); summary != "" {
		clioutput.Done("Pruned: %s (%s)", summary, elapsedSince(started))
		return nil
	}
	clioutput.Done("Nothing to prune (%s)", elapsedSince(started))
	return nil
}

// existingServiceFiles lists the service files prune works from, warning
// about a scan that ended early and going on with what it found.
func existingServiceFiles() []string {
	files, err := ggprune.ScanServiceFiles(ggconst.DirService)
	if err != nil {
		clioutput.Warn("failed to scan existing service files: %v", err)
	}
	return files
}

// existingPBFiles lists the files under pb/ prune works from, warning about
// a scan that ended early and going on with what it found.
func existingPBFiles() []string {
	files, err := ggprune.ScanPBFiles(ggconst.DirPB)
	if err != nil {
		clioutput.Warn("failed to scan existing protobuf files: %v", err)
	}
	return files
}

// staleDerivedPBFiles lists the Go files under pb/ gg gen does not write this
// run, generated being the paths it writes: the handlers and the plugins'
// files of a model deleted or no longer declaring GRPC(), which gg gen
// deletes itself. The definitions, the only files under pb/ a gst.yaml
// prune.ignore entry in protect keeps, are prune's to delete, so they are
// left out before the plan: a definition gg gen did not write is none of its
// concern, while a Go file there it did not generate fails the listing (see
// ggprune.PlanPBFiles).
func staleDerivedPBFiles(generated []string, protect ggconfig.PruneConfig) ([]string, error) {
	goFiles := slices.DeleteFunc(existingPBFiles(), func(path string) bool { return strings.HasSuffix(path, ggconst.ExtensionProto) })
	plan, err := ggprune.PlanPBFiles(goFiles, generated, protect)
	if err != nil {
		return nil, err
	}
	return plan.Delete, nil
}

// generatedPBFiles lists the paths of the files gg gen writes under pb/ for
// the current models, which prune keeps: the models are read the way gg gen
// reads them, the gst.yaml route and model ignores of projectCfg applied,
// since the files reflect them (unlike a service file, which an ignored
// action keeps on disk). The definitions and the Go files serving them are
// derived, the Go files compiled from the definitions are named from them
// (see compiledPBPaths) rather than compiled: prune only needs their names,
// and the plugins that compile them are not to be run, or fetched, for that.
func generatedPBFiles(ignore gghelper.ProjectIgnore, projectCfg *ggconfig.Config) ([]string, error) {
	scanned, err := scanModels(true, ignore, projectCfg)
	if err != nil {
		return nil, err
	}
	generated, err := protobufDefinitions(scanned.models, ignore)
	if err != nil {
		return nil, err
	}
	paths := make([]string, 0, 3*len(generated))
	for _, f := range generated {
		paths = append(paths, f.Path)
	}
	return append(paths, compiledPBPaths(generated)...), nil
}

// compiledPBPaths names the Go files pb.Compile writes for the definitions
// among files, the way the protobuf plugins name them: pb/record.pb.go for
// pb/record.proto, and pb/record_grpc.pb.go as well when the definition
// declares a service; the Go files among files, pb/record.gen.go, name
// nothing. For [pb/record.gen.go pb/record.proto pb/types.proto] with a
// service in the definition of record alone, the paths are
// [pb/record.pb.go pb/record_grpc.pb.go pb/types.pb.go]. A test holds this
// to what pb.Compile actually writes.
func compiledPBPaths(files []pb.File) []string {
	paths := make([]string, 0, 2*len(files))
	for _, f := range files {
		if !f.Definition() {
			continue
		}
		base := strings.TrimSuffix(f.Path, ggconst.ExtensionProto)
		paths = append(paths, base+ggconst.SuffixPBGo)
		if f.Service {
			paths = append(paths, base+ggconst.SuffixGRPCPBGo)
		}
	}
	return paths
}

// warnMissingPruneIgnore warns about the gst.yaml prune.ignore entries naming
// no file or directory, usually left behind by a rename; like the other
// gst.yaml warnings, it does not stop the run.
func warnMissingPruneIgnore(protect ggconfig.PruneConfig) {
	for _, entry := range protect.Ignore {
		if _, err := os.Stat(entry); os.IsNotExist(err) {
			clioutput.Warn("gst.yaml prune.ignore entry %q names no file or directory", entry)
		}
	}
}

// remindUnreadPruneSettings repeats, right before prune asks to delete, that
// a .gg.yaml protects nothing: the warning printed when gst.yaml was read may
// have scrolled away by then.
func remindUnreadPruneSettings() {
	for _, name := range ggconfig.UnreadFiles(".") {
		if ggconfig.IsLegacyPruneSettings(name) {
			clioutput.Warn("%s is not read, so the paths it lists are not protected here; move them into %s under prune.ignore", name, ggconfig.FileName)
		}
	}
}

// pruneLeftovers deletes, after asking once, what the models leave behind in
// service/, middleware/, interceptor/ and pb/: the service files of disabled
// actions among serviceFiles, the unmanaged files of the service directories
// no model owns, the middleware and interceptors module copy wrote for
// modules the project removed, with their register calls, the files under
// pb/ among pbFiles that gg gen would not write now, generatedPBFiles being
// the ones it writes, and the directories all this leaves empty. It works
// everything out before it asks, so a helper directory only a disabled
// action's service file imports goes in the same run. allModels carry the
// actions the gst.yaml route ignores take out of the generated registrations
// as well: their service files stay on disk, so they count as expected and
// are never deletion candidates. ignore, the project's ignore rules, decides
// which code counts as still using a service directory, as it decides what
// gg check and gg gen read; it protects nothing. The paths the gst.yaml
// prune.ignore entries in protect cover are never deleted: not as disabled
// files, not as orphans, not as empty directories; under pb/ an entry keeps
// the definitions alone (see ggprune.PlanPBFiles). Of the ignore rules, only
// those keep a path (see package ggprune). A file under pb/ it would delete
// that gg gen did not generate fails it before anything is asked or deleted
// (see ggprune.PlanPBFiles), a file it cannot delete once it has deleted the
// rest (see deleteLeftovers). What it removes is recorded in log; declined
// reports that the question was answered with a no, which it says itself.
func pruneLeftovers(log *changes, serviceFiles []string, allModels []*modelinfo.Model, ignore gghelper.ProjectIgnore, protect ggconfig.PruneConfig, pbFiles, generatedPBFiles []string) (declined bool, err error) {
	warnMissingPruneIgnore(protect)

	plan := ggprune.PlanFiles(serviceFiles, allModels, protect)
	pbPlan, err := ggprune.PlanPBFiles(pbFiles, generatedPBFiles, protect)
	if err != nil {
		return false, err
	}
	orphans, keptHelpers, keptHelperFiles, orphanHandlers := findOrphans(allModels, plan.Delete, ignore, protect)
	// A disabled action's file name inside a helper directory live code
	// imports names a file of that package: kept with the directory (see
	// ggprune.FindOrphanDirs), it leaves the deletion list.
	plan.Delete = slices.DeleteFunc(plan.Delete, func(file string) bool { return slices.Contains(keptHelperFiles, file) })
	nothingToDelete := len(plan.Delete) == 0 && len(orphans) == 0 && len(orphanHandlers) == 0 && len(pbPlan.Delete) == 0
	if nothingToDelete {
		removeEmptyDirs(protect, log)
	}
	if ignored := append(slices.Clone(plan.Ignored), pbPlan.Ignored...); len(ignored) > 0 {
		clioutput.Section("Files Ignored By Config")
		for _, file := range ignored {
			clioutput.Item("ignore %s", file)
		}
	}
	reportKeptServiceHelperDirs(keptHelpers, keptHelperFiles)
	if nothingToDelete {
		return false, nil
	}

	if len(plan.Delete) > 0 {
		clioutput.Section("Disabled Service Files")
		for _, file := range plan.Delete {
			clioutput.Status(clioutput.StyleError, clioutput.SymbolError, "%s", file)
		}
	}
	reportOrphanServiceDirs(orphans)
	reportOrphanModuleFiles(orphanHandlers)
	if len(pbPlan.Delete) > 0 {
		clioutput.Section("Stale Protobuf Files")
		for _, file := range pbPlan.Delete {
			clioutput.Status(clioutput.StyleError, clioutput.SymbolError, "%s", file)
		}
		if slices.ContainsFunc(pbPlan.Delete, func(file string) bool { return strings.HasSuffix(file, ggconst.ExtensionProto) }) {
			clioutput.Warn("A definition goes with the numbers and names it reserves: a client built against it would read a new field under a number a removed one held, so move its reservations into the definition replacing it first")
		}
	}
	remindUnreadPruneSettings()
	// Orphan middleware and interceptors carry the ownership marker module
	// copy wrote; only an orphan directory holds files gg cannot vouch for.
	if len(orphans) > 0 {
		clioutput.Warn("This will delete unmanaged files that gg cannot prove it owns.")
	}
	if !clioutput.Confirm("Do you want to delete these files?") {
		clioutput.Item("Deletion canceled")
		return true, nil
	}

	return false, deleteLeftovers(log, plan.Delete, orphans, orphanHandlers, pbPlan.Delete, protect)
}

// findOrphans works out the orphans prune deletes along with deleting, the
// service files it deletes anyway: the service directories no model owns,
// see ggprune.FindOrphanDirs for the ownership rules, and the middleware and
// interceptors module copy wrote for modules the project removed, see
// orphanModuleFiles. It returns as well the helper directories kept
// because live code imports them, with the files of deleting kept along
// with them. When the project's code cannot be read in full, it warns and
// finds no orphans.
func findOrphans(allModels []*modelinfo.Model, deleting []string, ignore gghelper.ProjectIgnore, protect ggconfig.PruneConfig) (orphans, keptHelpers []ggprune.OrphanDir, keptFiles []string, orphanHandlers []ggmodule.OrphanManagedFile) {
	orphanHandlers, err := orphanModuleFiles(protect)
	if err != nil {
		clioutput.Warn("failed to read the middleware or interceptor directory, so orphans are not checked: %v", err)
		return nil, nil, nil, nil
	}
	deleting = slices.Clone(deleting)
	for _, file := range orphanHandlers {
		deleting = append(deleting, file.Path)
	}
	orphans, keptHelpers, keptFiles, err = ggprune.FindOrphanDirs(allModels, deleting, module, ignore, protect)
	if err != nil {
		clioutput.Warn("failed to trace which service directories live code imports, so orphan service directories are not checked: %v", err)
		return nil, nil, nil, nil
	}
	return orphans, keptHelpers, keptFiles, orphanHandlers
}

// deleteLeftovers deletes what pruneLeftovers listed, in this order: the
// disabled service files, the orphan middleware and interceptors with their
// register calls, the unmanaged files of the orphan service directories, the
// stale files under pb/, and last the directories this leaves empty. The
// orphan directories are orphans because the files before them go, so when
// one of those cannot be deleted they stay. What it cannot delete does not
// stop it: it deletes the rest, the way rm goes on past an operand it cannot
// remove, and then fails, naming what stayed, so that the command does not
// report a success. What it deletes is recorded in log.
func deleteLeftovers(log *changes, disabledFiles []string, orphans []ggprune.OrphanDir, orphanHandlers []ggmodule.OrphanManagedFile, stalePBFiles []string, protect ggconfig.PruneConfig) error {
	var errs []error
	var kept []string
	report := func(path string, err error) {
		if err != nil {
			kept = append(kept, path)
			clioutput.Error("Failed to delete %s: %v", path, err)
			return
		}
		log.record(clioutput.LabelRemove, path, "")
	}
	ggprune.RemoveFiles(disabledFiles, report)
	disabledKept := len(kept) > 0
	if len(orphanHandlers) > 0 {
		if err := cleanOrphanModuleFiles(orphanHandlers, module, log); err != nil {
			clioutput.Error("Failed to delete orphan module middleware or interceptor files, so orphan service directories are kept: %v", err)
			orphans = nil
			errs = append(errs, err)
		}
	}
	if disabledKept && len(orphans) > 0 {
		clioutput.Warn("Some disabled service files were not deleted, so orphan service directories are kept")
		orphans = nil
	}
	var orphanFiles []string
	for _, orphan := range orphans {
		orphanFiles = append(orphanFiles, orphan.Files...)
	}
	ggprune.RemoveFiles(orphanFiles, report)
	ggprune.RemoveFiles(stalePBFiles, report)
	removeEmptyDirs(protect, log)
	if len(kept) > 0 {
		errs = append(errs, errors.Newf("failed to delete %s", strings.Join(kept, ", ")))
	}
	return errors.Join(errs...)
}

// removeEmptyDirs removes the empty directories below the service and pb
// directories that prune.ignore does not cover, recording each one in log.
// The service directory itself stays, the project's scaffold owning it; the
// pb directory goes with its last definition, gg gen alone having created
// it.
func removeEmptyDirs(protect ggconfig.PruneConfig, log *changes) {
	report := func(dir string) {
		log.record(clioutput.LabelRemove, dir, " (an empty directory)")
	}
	ggprune.RemoveEmptyDirs(ggconst.DirService, protect, report)
	if !gghelper.FileExists(ggconst.DirPB) {
		return
	}
	ggprune.RemoveEmptyDirs(ggconst.DirPB, protect, report)
	if !protect.Ignores(ggconst.DirPB) {
		if err := os.Remove(ggconst.DirPB); err == nil {
			report(ggconst.DirPB)
		}
	}
}

// orphanModuleFiles lists the middleware and interceptor files module copy
// wrote for modules the project removed (see ggmodule.OrphanManagedFiles),
// middleware first, but for the ones a gst.yaml prune.ignore entry in
// protect covers, which stay live code; no other rule keeps a file, a Git
// ignored one included.
func orphanModuleFiles(protect ggconfig.PruneConfig) ([]ggmodule.OrphanManagedFile, error) {
	var orphans []ggmodule.OrphanManagedFile
	for _, dir := range []string{ggconst.DirMiddleware, ggconst.DirInterceptor} {
		found, err := ggmodule.OrphanManagedFiles(dir, ggconst.DirModel)
		if err != nil {
			return nil, err
		}
		orphans = append(orphans, found...)
	}
	return slices.DeleteFunc(orphans, func(orphan ggmodule.OrphanManagedFile) bool {
		return protect.Ignores(orphan.Path)
	}), nil
}

// reportOrphanModuleFiles lists the orphan middleware files and the orphan
// interceptor files under a heading each; every file goes together with its
// register calls.
func reportOrphanModuleFiles(orphans []ggmodule.OrphanManagedFile) {
	for _, group := range []struct{ dir, title string }{
		{ggconst.DirMiddleware, "Orphan Module Middleware Files"},
		{ggconst.DirInterceptor, "Orphan Module Interceptor Files"},
	} {
		first := true
		for _, orphan := range orphans {
			if filepath.Dir(orphan.Path) != group.dir {
				continue
			}
			if first {
				clioutput.Section(group.title)
				first = false
			}
			clioutput.Item("%s (copied with module %s, whose %s is gone; its register calls go with it)", orphan.Path, orphan.Module, filepath.Join(ggconst.DirModel, orphan.Module))
		}
	}
}

// cleanOrphanModuleFiles deletes the orphan middleware and interceptor files
// and their register calls, directory by directory, recording in log each
// file it deletes or changes.
func cleanOrphanModuleFiles(orphans []ggmodule.OrphanManagedFile, modulePath string, log *changes) error {
	for _, dir := range []string{ggconst.DirMiddleware, ggconst.DirInterceptor} {
		var files []string
		for _, orphan := range orphans {
			if filepath.Dir(orphan.Path) == dir {
				files = append(files, orphan.Path)
			}
		}
		if len(files) == 0 {
			continue
		}
		err := ggmodule.RemoveManagedFiles(dir, files, modulePath, func(status ggmodule.CopyWriteStatus, path string) {
			if status == ggmodule.CopyWriteDelete {
				log.record(clioutput.LabelRemove, path, "")
				return
			}
			log.record(clioutput.LabelUpdate, path, " (their register calls removed)")
		})
		if err != nil {
			return err
		}
	}
	return nil
}

// reportOrphanServiceDirs lists the orphan service directories, each with the
// unmanaged files cleaning it deletes.
func reportOrphanServiceDirs(orphans []ggprune.OrphanDir) {
	if len(orphans) == 0 {
		return
	}
	clioutput.Section("Unmanaged Orphan Service Directories")
	for _, orphan := range orphans {
		clioutput.Item("%s (no current model maps to this directory)", orphan.Path)
		for _, file := range orphan.Files {
			clioutput.Detail("%s", file)
		}
	}
}

// reportKeptServiceHelperDirs explains why unmanaged helper directories are
// no orphans: live project code still imports them.
func reportKeptServiceHelperDirs(keptHelpers []ggprune.OrphanDir, keptFiles []string) {
	if len(keptHelpers) == 0 {
		return
	}
	clioutput.Section("Service Helper Directories Kept")
	for _, helper := range keptHelpers {
		clioutput.Item("%s (imported by live project code)", helper.Path)
	}
	for _, file := range keptFiles {
		clioutput.Item("%s (part of a kept helper package, not a disabled service file)", file)
	}
}
