// TestGenRunAliasesCollidingImports pins how gg gen names the imports of the
// generated registration files. A project package keeps its package name
// unless that name is already taken in the file, by a framework package the
// file imports or by another project package. Every package in such a clash
// is imported under an alias built from its last path segments, and its
// registrations refer to it through the alias; the framework packages keep
// their names. Each case writes a few model files, runs gg gen, compares the
// registration files it writes as a whole, and builds the project.
func TestGenRunAliasesCollidingImports(t *testing.T) {
	modelFile := filepath.Join("model", constants.FileModelGen)
	serviceFile := filepath.Join("service", constants.FileServiceGen)
	routerFile := filepath.Join("router", constants.FileRouterGen)

	tests := []struct {
		name  string
		files map[string]string
		// want maps each generated file to its whole content.
		want map[string]string
	}{
		{
			// The service package of a model named Service is named service,
			// like the framework package the file imports; the service
			// package of Item keeps its name.
			name: "service_file_aliases_a_package_named_like_a_framework_import",
			files: map[string]string{
				"model/sample/service.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Service struct {
	model.Empty
}

func (Service) Design() {
	dsl.Endpoint("services")
	dsl.Create(func() {
		dsl.Service()
	})
}
`,
				"model/sample/item.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Item struct {
	model.Empty
}

func (Item) Design() {
	dsl.Endpoint("items")
	dsl.Create(func() {
		dsl.Service()
	})
}
`,
			},
			want: map[string]string{
				serviceFile: `// Code generated by gst; DO NOT EDIT.

package service

import (
	"tmpapp/service/sample/item"
	sample_service "tmpapp/service/sample/service"

	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/service"
)

func init() {
	service.Register[*item.Creator](consts.PHASE_CREATE, "sample/items")
	service.Register[*sample_service.Creator](consts.PHASE_CREATE, "sample/services")
}
`,
			},
		},
		{
			// Both RecordItem models have a service package named
			// recorditem, in directories named after their model files, so
			// both are aliased, not just one of them; the service package of
			// Item keeps its name.
			name: "service_file_aliases_every_package_sharing_a_name",
			files: map[string]string{
				"model/sample/record_item.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type RecordItem struct {
	model.Empty
}

func (RecordItem) Design() {
	dsl.Endpoint("record-items")
	dsl.Create(func() {
		dsl.Service()
	})
}
`,
				"model/account/recorditem.go": `package account

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type RecordItem struct {
	model.Empty
}

func (RecordItem) Design() {
	dsl.Endpoint("record-items")
	dsl.Create(func() {
		dsl.Service()
	})
}
`,
				"model/sample/item.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Item struct {
	model.Empty
}

func (Item) Design() {
	dsl.Endpoint("items")
	dsl.Create(func() {
		dsl.Service()
	})
}
`,
			},
			want: map[string]string{
				serviceFile: `// Code generated by gst; DO NOT EDIT.

package service

import (
	account_recorditem "tmpapp/service/account/recorditem"
	"tmpapp/service/sample/item"
	sample_record_item "tmpapp/service/sample/record_item"

	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/service"
)

func init() {
	service.Register[*account_recorditem.Creator](consts.PHASE_CREATE, "account/record-items")
	service.Register[*item.Creator](consts.PHASE_CREATE, "sample/items")
	service.Register[*sample_record_item.Creator](consts.PHASE_CREATE, "sample/record-items")
}
`,
			},
		},
		{
			// A package named model below the root model package takes the
			// name of the framework package the file imports; the sample
			// package keeps its name.
			name: "model_file_aliases_a_package_named_like_a_framework_import",
			files: map[string]string{
				"model/sample/model/entry.go": `package model

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Entry struct {
	model.Base
}

func (Entry) TableName() string { return "sample_entries" }

func (Entry) Design() {
	dsl.Migrate()
}
`,
				"model/sample/record.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Record struct {
	model.Base
}

func (Record) TableName() string { return "sample_records" }

func (Record) Design() {
	dsl.Migrate()
}
`,
			},
			want: map[string]string{
				modelFile: `// Code generated by gst; DO NOT EDIT.

package model

import (
	"tmpapp/model/sample"
	sample_model "tmpapp/model/sample/model"

	"github.com/hydroan/gst/model"
)

func init() {
	model.Register[*sample_model.Entry]()
	model.Register[*sample.Record]()
}
`,
			},
		},
		{
			// Both packages are named sample, so both are aliased; the
			// account package keeps its name.
			name: "model_file_aliases_every_package_sharing_a_name",
			files: map[string]string{
				"model/tenant/sample/record.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Record struct {
	model.Base
}

func (Record) TableName() string { return "tenant_records" }

func (Record) Design() {
	dsl.Migrate()
}
`,
				"model/account/sample/entry.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Entry struct {
	model.Base
}

func (Entry) TableName() string { return "account_entries" }

func (Entry) Design() {
	dsl.Migrate()
}
`,
				"model/account/item.go": `package account

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Item struct {
	model.Base
}

func (Item) TableName() string { return "account_items" }

func (Item) Design() {
	dsl.Migrate()
}
`,
			},
			want: map[string]string{
				modelFile: `// Code generated by gst; DO NOT EDIT.

package model

import (
	"tmpapp/model/account"
	account_sample "tmpapp/model/account/sample"
	tenant_sample "tmpapp/model/tenant/sample"

	"github.com/hydroan/gst/model"
)

func init() {
	model.Register[*account.Item]()
	model.Register[*account_sample.Entry]()
	model.Register[*tenant_sample.Record]()
}
`,
			},
		},
		{
			// The gst and router packages take the names of framework
			// packages the router file imports; the sample package keeps its
			// name. The model file imports no framework package named gst,
			// so the gst package keeps its name there: every file decides
			// its own aliases. A model package cannot be named consts: model
			// directories are singular, and const is a keyword.
			name: "router_file_aliases_packages_named_like_framework_imports",
			files: map[string]string{
				"model/gst/item.go": `package gst

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Item struct {
	model.Base
}

func (Item) TableName() string { return "gst_items" }

func (Item) Design() {
	dsl.Migrate()
	dsl.Endpoint("items")
	dsl.Create(func() {})
}
`,
				"model/router/entry.go": `package router

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Entry struct {
	model.Empty
}

func (Entry) Design() {
	dsl.Endpoint("entries")
	dsl.Create(func() {})
}
`,
				"model/sample/record.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Record struct {
	model.Empty
}

func (Record) Design() {
	dsl.Endpoint("records")
	dsl.Create(func() {})
}
`,
			},
			want: map[string]string{
				routerFile: `// Code generated by gst; DO NOT EDIT.

package router

import (
	model_gst "tmpapp/model/gst"
	model_router "tmpapp/model/router"
	"tmpapp/model/sample"

	"github.com/hydroan/gst"
	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/router"
)

func Init() error {
	router.Register[*model_gst.Item, *model_gst.Item, *model_gst.Item](router.Auth(), "gst/items", &gst.ControllerConfig[*model_gst.Item]{}, consts.Create)
	router.Register[*model_router.Entry, *model_router.Entry, *model_router.Entry](router.Auth(), "router/entries", &gst.ControllerConfig[*model_router.Entry]{}, consts.Create)
	router.Register[*sample.Record, *sample.Record, *sample.Record](router.Auth(), "sample/records", &gst.ControllerConfig[*sample.Record]{}, consts.Create)
	return nil
}
`,
				modelFile: `// Code generated by gst; DO NOT EDIT.

package model

import (
	"tmpapp/model/gst"

	"github.com/hydroan/gst/model"
)

func init() {
	model.Register[*gst.Item]()
}
`,
			},
		},
		{
			// The root model package and a package named model below it are
			// both aliased; the sample package keeps its name. The framework
			// model package, imported for the model.Empty request of a List
			// declaring only its result, keeps the gstmodel alias it has
			// always taken when a routed project package is named model.
			name: "router_file_aliases_every_package_sharing_a_name",
			files: map[string]string{
				"model/record.go": `package model

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Record struct {
	model.Empty
}

type RecordListRsp struct{}

func (Record) Design() {
	dsl.Endpoint("records")
	dsl.List(func() {
		dsl.Result[*RecordListRsp]()
	})
}
`,
				"model/sample/model/item.go": `package model

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Item struct {
	model.Empty
}

func (Item) Design() {
	dsl.Endpoint("items")
	dsl.Create(func() {})
}
`,
				"model/sample/entry.go": `package sample

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Entry struct {
	model.Empty
}

func (Entry) Design() {
	dsl.Endpoint("entries")
	dsl.Create(func() {})
}
`,
			},
			want: map[string]string{
				routerFile: `// Code generated by gst; DO NOT EDIT.

package router

import (
	tmpapp_model "tmpapp/model"
	"tmpapp/model/sample"
	sample_model "tmpapp/model/sample/model"

	"github.com/hydroan/gst"
	"github.com/hydroan/gst/consts"
	gstmodel "github.com/hydroan/gst/model"
	"github.com/hydroan/gst/router"
)

func Init() error {
	router.Register[*tmpapp_model.Record, *gstmodel.Empty, *tmpapp_model.RecordListRsp](router.Auth(), "records", &gst.ControllerConfig[*tmpapp_model.Record]{}, consts.List)
	router.Register[*sample.Entry, *sample.Entry, *sample.Entry](router.Auth(), "sample/entries", &gst.ControllerConfig[*sample.Entry]{}, consts.Create)
	router.Register[*sample_model.Item, *sample_model.Item, *sample_model.Item](router.Auth(), "sample/model/items", &gst.ControllerConfig[*sample_model.Item]{}, consts.Create)
	return nil
}
`,
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			projectDir := newGenProject(t)
			for path, content := range tt.files {
				writeCheckFile(t, filepath.Join(projectDir, path), content)
			}

			require.NoError(t, genRunWithOptions(genRunOptions{Quiet: true}))
			for file, want := range tt.want {
				got, err := os.ReadFile(file)
				require.NoError(t, err)
				require.Equal(t, want, string(got), file)
			}

			output, err := exec.Command("go", "build", "-mod=mod", "./...").CombinedOutput()
			require.NoError(t, err, "go build:\n%s", output)
		})
	}
}
