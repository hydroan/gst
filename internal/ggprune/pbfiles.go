// ScanPBFiles lists the files gg gen writes under pbDir, the directory the
// protobuf definitions, the Go files serving them and the Go files compiled
// from them go to, in walk order: pb/pb.gen.go, pb/record/item.gen.go,
// pb/record/item.pb.go, pb/record/item.proto, pb/record/item_grpc.pb.go,
// pb/record/pb.gen.go, pb/record.gen.go, pb/record.pb.go, pb/record.proto and
// pb/record_grpc.pb.go for a project serving Record and its child Item over
// gRPC. Only the .proto, .gen.go and .pb.go files are listed, the kinds gg gen
// writes. Like ScanServiceFiles it reads the directory whole, the directory
// being gg's: a file the project's Git ignore rules cover, or one below a
// directory the go command leaves out, is listed like any other. A missing
// directory lists nothing.
func ScanPBFiles(pbDir string) ([]string, error) {
	var files []string
	if _, err := os.Stat(pbDir); os.IsNotExist(err) {
		return files, nil
	}
	err := filepath.Walk(pbDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && (strings.HasSuffix(info.Name(), ggconst.ExtensionProto) || strings.HasSuffix(info.Name(), ggconst.SuffixGenGo) || strings.HasSuffix(info.Name(), ggconst.SuffixPBGo)) {
			files = append(files, path)
		}
		return nil
	})
	return files, err
}

// PlanPBFiles works out which of the existing files under pb/ prune deletes:
// the ones gg gen would not write now, generated being the paths it writes,
// slash-separated as pb.Generate and pb.Compile hand them out. Of existing
// [pb/record.proto pb/record.pb.go pb/note.proto pb/legacy/item.proto
// pb/legacy/item.pb.go] and generated [pb/record.proto pb/record.pb.go], the
// plan deletes pb/note.proto and pb/legacy/item.pb.go and, with a gst.yaml
// prune.ignore entry pb/legacy in protect, keeps pb/legacy/item.proto under
// Ignored: an entry keeps the definitions alone. The files are the models'
// mirror, rewritten by every gg gen, so unlike a service file nothing in them
// is the project's to keep, but for the numbers and names a definition
// reserves: gg gen deletes the stale Go files itself, as it writes, and
// leaves the definitions to prune, which warns of the reservations going with
// them.
//
// Only a file opening with the header gg gen writes, "// Code generated by
// gst; DO NOT EDIT.", is gg's to delete; one opening with anything else, the
// stubs a project compiled itself for a service it calls, fails the plan,
// naming every such file. Of existing [pb/record.proto
// pb/upstream/upstream.pb.go pb/upstream/upstream_grpc.pb.go
// pb/legacy/client.proto], none of the last three opening with the header,
// and generated [pb/record.proto], with the entry pb/legacy in protect, the
// plan fails with
//
//	files under pb/ named like the ones gg gen writes but not generated by gst: pb/upstream/upstream.pb.go, pb/upstream/upstream_grpc.pb.go; gg deletes only its own files there, so rename these or move them out of pb/
//
// pb/legacy/client.proto being kept under the entry without being read.
func PlanPBFiles(existing, generated []string, protect ggconfig.PruneConfig) (FilePlan, error) {
	current := make([]string, 0, len(generated))
	for _, path := range generated {
		current = append(current, filepath.Clean(filepath.FromSlash(path)))
	}
	var plan FilePlan
	var foreign []string
	for _, path := range existing {
		if slices.Contains(current, filepath.Clean(path)) {
			continue
		}
		if strings.HasSuffix(path, ggconst.ExtensionProto) && protect.Ignores(path) {
			plan.Ignored = append(plan.Ignored, path)
			continue
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return FilePlan{}, errors.Wrapf(err, "read %s", path)
		}
		if !bytes.HasPrefix(content, []byte(consts.CodeGeneratedComment())) {
			foreign = append(foreign, path)
			continue
		}
		plan.Delete = append(plan.Delete, path)
	}
	if len(foreign) > 0 {
		return FilePlan{}, errors.Newf("files under %s/ named like the ones gg gen writes but not generated by gst: %s; gg deletes only its own files there, so rename these or move them out of %s/",
			ggconst.DirPB, strings.Join(foreign, ", "), ggconst.DirPB)
	}
	return plan, nil
}
