// TestScanPBFilesListsTheGeneratedFilesWhole pins that prune reads the pb
// directory whole: every .proto, .gen.go and .pb.go file under it is listed,
// one the project's Git ignore rules exclude and one below a directory named
// with a leading "_" included, other files are not, and a missing directory
// lists nothing.
func TestScanPBFilesListsTheGeneratedFilesWhole(t *testing.T) {
	projectDir := t.TempDir()
	t.Chdir(projectDir)
	writeProjectFile(t, ".gitignore", "pb/record/item.proto\n")
	want := []string{
		filepath.Join(ggconst.DirPB, "_old", "draft.proto"),
		filepath.Join(ggconst.DirPB, ggconst.FilePBGen),
		filepath.Join(ggconst.DirPB, "record.gen.go"),
		filepath.Join(ggconst.DirPB, "record.pb.go"),
		filepath.Join(ggconst.DirPB, "record.proto"),
		filepath.Join(ggconst.DirPB, "record", "item.proto"),
		filepath.Join(ggconst.DirPB, "record_grpc.pb.go"),
	}
	for _, path := range want {
		writeProjectFile(t, path, "generated\n")
	}
	writeProjectFile(t, filepath.Join(ggconst.DirPB, "README.md"), "notes\n")

	got, err := ggprune.ScanPBFiles(ggconst.DirPB)
	if err != nil {
		t.Fatal(err)
	}
	slices.Sort(got)
	if !slices.Equal(got, want) {
		t.Fatalf("ScanPBFiles() = %v, want %v", got, want)
	}

	none, err := ggprune.ScanPBFiles(filepath.Join(projectDir, "missing"))
	if err != nil || len(none) != 0 {
		t.Fatalf("ScanPBFiles(missing) = %v, %v; want nothing and no error", none, err)
	}
}

// TestPlanPBFilesDeletesWhatGenWouldNotWrite pins that the plan deletes
// every existing file gg gen would not write now, each opening with the
// header gg gen writes, definitions and the Go files compiled from them
// alike, in the order they were scanned, keeps of the files a gst.yaml
// prune.ignore entry covers only the definitions, under Ignored, the Go
// files below the entry going with the rest, and reads the generated paths
// as gg gen hands them out, slash-separated.
func TestPlanPBFilesDeletesWhatGenWouldNotWrite(t *testing.T) {
	t.Chdir(t.TempDir())
	current := filepath.Join(ggconst.DirPB, "record.proto")
	currentGo := filepath.Join(ggconst.DirPB, "record.pb.go")
	currentItem := filepath.Join(ggconst.DirPB, "record", "item.proto")
	stale := filepath.Join(ggconst.DirPB, "note.proto")
	staleGo := filepath.Join(ggconst.DirPB, "note_grpc.pb.go")
	staleHandlers := filepath.Join(ggconst.DirPB, "note.gen.go")
	kept := filepath.Join(ggconst.DirPB, "legacy", "item.proto")
	keptGo := filepath.Join(ggconst.DirPB, "legacy", "item.pb.go")
	keptHandlers := filepath.Join(ggconst.DirPB, "legacy", "item.gen.go")
	protect := ggconfig.PruneConfig{Ignore: []string{"pb/legacy"}}
	existing := []string{current, stale, kept, keptGo, currentItem, currentGo, staleGo, staleHandlers, keptHandlers}
	for _, path := range existing {
		writeProjectFile(t, path, consts.CodeGeneratedComment()+"\n")
	}

	plan, err := ggprune.PlanPBFiles(existing, []string{"pb/record.proto", "pb/record/item.proto", "pb/record.pb.go"}, protect)
	if err != nil {
		t.Fatal(err)
	}

	wantDelete := []string{stale, keptGo, staleGo, staleHandlers, keptHandlers}
	if !slices.Equal(plan.Delete, wantDelete) {
		t.Errorf("Delete = %v, want %v", plan.Delete, wantDelete)
	}
	if !slices.Equal(plan.Ignored, []string{kept}) {
		t.Errorf("Ignored = %v, want %v", plan.Ignored, []string{kept})
	}
}

// TestPlanPBFilesRefusesTheFilesGenDidNotGenerate pins that a file the plan
// would delete without the header gg gen writes fails it, naming every such
// file, while one a gst.yaml prune.ignore entry keeps is not read: it is not
// even on disk. Guards PlanPBFiles's example.
func TestPlanPBFilesRefusesTheFilesGenDidNotGenerate(t *testing.T) {
	t.Chdir(t.TempDir())
	writeProjectFile(t, "pb/record.proto", consts.CodeGeneratedComment()+"\n")
	for _, path := range []string{"pb/upstream/upstream.pb.go", "pb/upstream/upstream_grpc.pb.go"} {
		writeProjectFile(t, path, "// Code generated by protoc-gen-go. DO NOT EDIT.\n")
	}

	_, err := ggprune.PlanPBFiles([]string{"pb/record.proto", "pb/upstream/upstream.pb.go", "pb/upstream/upstream_grpc.pb.go", "pb/legacy/client.proto"},
		[]string{"pb/record.proto"}, ggconfig.PruneConfig{Ignore: []string{"pb/legacy"}})

	want := "files under pb/ named like the ones gg gen writes but not generated by gst: pb/upstream/upstream.pb.go, pb/upstream/upstream_grpc.pb.go; gg deletes only its own files there, so rename these or move them out of pb/"
	if err == nil || err.Error() != want {
		t.Fatalf("PlanPBFiles() error = %v, want %q", err, want)
	}
}
