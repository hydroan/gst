// Package ggconst holds the conventions the framework's tooling shares: the
// import paths of the framework packages, the names of the files, packages,
// fields and symbols gg generates and reads, and the patterns it recognizes
// them by. The dsl parser, the syntax tree helpers of goast, the code
// generator and the gg commands all read them from here, so a convention is
// spelled once.
package ggconst

import "github.com/hydroan/gst/internal/gst"

// Import paths
const (
	// Framework import paths
	//nolint:godoclint
	ImportPathGst       = "github.com/hydroan/gst"
	ImportPathModel     = "github.com/hydroan/gst/model"
	ImportPathService   = "github.com/hydroan/gst/service"
	ImportPathRouter    = "github.com/hydroan/gst/router"
	ImportPathBootstrap = "github.com/hydroan/gst/bootstrap"
	ImportPathAPIDoc    = "github.com/hydroan/gst/apidoc"
	ImportPathGRPC      = "github.com/hydroan/gst/grpc"
	ImportPathDatatypes = "github.com/hydroan/gst/datatypes"

	// ImportPathInternalModel is the package the public model package
	// forwards, where the framework's own model types are declared: the path
	// reflection and the type checker report for model.Base, model.Empty and
	// their siblings. The tooling tells those types by it; generated code
	// imports ImportPathModel.
	ImportPathInternalModel = ImportPathGst + "/internal/model"

	// ImportPathIO is the standard library package the Import method of a
	// generated service file reads its input through.
	ImportPathIO = "io"
)

// File extensions and name suffixes
const (
	ExtensionGo    = ".go"
	ExtensionProto = ".proto"
	// SuffixTestFile ends the name of a test file: create_test.go beside
	// create.go.
	SuffixTestFile = "_test.go"
	// SuffixInternalTestFile ends the name of an internal test file, the
	// test file of a package that reaches its unexported code:
	// create_internal_test.go beside create.go.
	SuffixInternalTestFile = "_internal" + SuffixTestFile
	// SuffixTestPkg ends the name of an external test package: record_test
	// for the package record.
	SuffixTestPkg = "_test"
)

// FileModeGenerated is the permission gg writes project files with.
//
// Generated sources are ordinary source files and must be as readable as the
// hand-written ones next to them: a stricter mode leaves the package with
// mixed permissions and breaks any reader that is not the generating user,
// such as a CI job or a container build running as another account. The
// process umask still tightens this as configured.
const FileModeGenerated = 0o644

// CodeGeneratedComment is the first line of every file gg generates, the
// comment the Go toolchain and the editors recognize a generated file by
// (https://go.dev/s/generatedcode); gg tells the files it owns by it.
const CodeGeneratedComment = "// Code generated by " + gst.FrameworkName + "; DO NOT EDIT."

// Generated file names.
//
// SuffixGenGo marks every file gg generates and fully owns. A file carrying
// this suffix is framework-managed: gg rewrites it, and deletes it once the
// source it was generated from is gone. Project code never has to clean up
// after the generator.
const (
	SuffixGenGo = ".gen.go"
	// SuffixPBGo and SuffixGRPCPBGo are the suffixes protoc-gen-go and
	// protoc-gen-go-grpc give the Go files they compile from a definition:
	// record.proto compiles to record.pb.go and record_grpc.pb.go.
	SuffixPBGo     = ".pb.go"
	SuffixGRPCPBGo = "_grpc.pb.go"

	FileModelGen   = "model" + SuffixGenGo
	FileAPIDocGen  = "apidoc" + SuffixGenGo
	FileServiceGen = "service" + SuffixGenGo
	FileRouterGen  = "router" + SuffixGenGo
	// FilePBGen registers the gRPC services of a project, under DirPB.
	FilePBGen = "pb" + SuffixGenGo
	// FileMain keeps its conventional name: main.go is the entry point every
	// Go toolchain and IDE expects.
	FileMain = "main.go"
)

// FileMainTest names the test file gg check reserves for a package's
// TestMain: it declares TestMain and nothing else.
const FileMainTest = "main_test.go"

