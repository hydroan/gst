package gen

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/token"
	"path"
	"slices"
	"strconv"
	"strings"
	"unicode"

	goimports "golang.org/x/tools/imports"
	fumpt "mvdan.cc/gofumpt/format"
)

// formatOnlyImports runs goimports as an import formatter only. Its import
// fixing resolves unknown qualifiers by scanning the whole module cache for a
// package that could supply them, which costs seconds per file and cannot tell
// a package qualifier from any other selector in a single file. Every caller
// here builds its own import set, so there is nothing left for it to fix.
var formatOnlyImports = &goimports.Options{Comments: true, TabIndent: true, TabWidth: 8, FormatOnly: true}

// FormatNode use go standard lib "go/format" to format ast.Node into code.
func FormatNode(node ast.Node, processImport ...bool) (string, error) {
	var buf bytes.Buffer
	fset := token.NewFileSet()

	if err := format.Node(&buf, fset, node); err != nil {
		return "", err
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return "", err
	}

	// Fix comment position: move comments that appear on package line to separate line
	formattedStr := string(formatted)
	formattedStr = fixCommentPosition(formattedStr)

	if len(processImport) > 0 && processImport[0] {
		result, err := goimports.Process("", []byte(formattedStr), formatOnlyImports)
		if err != nil {
			return "", err
		}
		return string(result), nil
	}

	return formattedStr, nil
}

// FormatNodeExtra use "https://github.com/mvdan/gofumpt" to format ast.Node into code.
func FormatNodeExtra(node ast.Node, processImport ...bool) (string, error) {
	return FormatNodeExtraWithFileSet(node, nil, processImport...)
}

// FormatNodeExtraWithFileSet formats the node with the given FileSet, which keeps comments in place.
func FormatNodeExtraWithFileSet(node ast.Node, fset *token.FileSet, processImport ...bool) (string, error) {
	var buf bytes.Buffer
	// create a new FileSet if none was provided
	if fset == nil {
		fset = token.NewFileSet()
	}

	if err := format.Node(&buf, fset, node); err != nil {
		return "", err
	}

	formatted, err := fumpt.Source(buf.Bytes(), fumpt.Options{
		LangVersion: "",
		Extra:       fumpt.Extra{GroupParams: true, ClotheReturns: true, BalanceCalls: true},
	})
	if err != nil {
		return "", err
	}

	// Fix comment position: move comments that appear on package line to separate line
	formattedStr := string(formatted)
	formattedStr = fixCommentPosition(formattedStr)

	if len(processImport) > 0 && processImport[0] {
		var result []byte
		if result, err = goimports.Process("", []byte(formattedStr), formatOnlyImports); err != nil {
			return "", err
		}
		return string(result), nil
	}

	return formattedStr, nil
}

// fixCommentPosition fixes the position of the generated header: on a line
// of its own above the package clause, with a blank line between the two —
// a comment right above the clause would be the package's doc, and a
// project's own package doc beside it would be a second one — and a blank
// line after the clause.
func fixCommentPosition(code string) string {
	lines := strings.Split(code, "\n")
	normalized := make([]string, 0, len(lines)+1)

	for _, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "package ") {
			if commentIdx := strings.Index(line, "// Code generated by"); commentIdx != -1 {
				packageDecl := strings.TrimSpace(line[:commentIdx])
				comment := strings.TrimSpace(line[commentIdx:])
				normalized = append(normalized, comment, packageDecl)
				continue
			}
		}
		normalized = append(normalized, line)
	}
	lines = normalized

	packageLineIndex := -1
	for i, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "package ") {
			packageLineIndex = i
			break
		}
	}

	if packageLineIndex > 0 && strings.HasPrefix(lines[packageLineIndex-1], "// Code generated by") {
		lines = append(lines[:packageLineIndex], append([]string{""}, lines[packageLineIndex:]...)...)
		packageLineIndex++
	}

	if packageLineIndex != -1 && packageLineIndex+1 < len(lines) && strings.TrimSpace(lines[packageLineIndex+1]) != "" {
		lines = append(lines[:packageLineIndex+1], append([]string{""}, lines[packageLineIndex+1:]...)...)
	}

	return strings.Join(lines, "\n")
}

// ResolveImportConflicts picks the alias each import of a generated file
// needs. An import keeps its package name, taken as its last path segment,
// unless another import shares it; then it is aliased with its last two
// segments joined by an underscore ("svc/pkg1/user" becomes "pkg1_user"). An
// alias that still clashes with another import's name takes one more leading
// segment at a time, and one that runs out of segments gets a numeric suffix,
// so no two imports share a name. Every alias is a Go identifier: characters
// an identifier cannot hold become underscores, and one that would start with
// a digit gets an underscore in front. The result maps each import path to its
// alias, or to "" when it needs none.
func ResolveImportConflicts(imports []string) map[string]string {
	paths := slices.Compact(slices.Sorted(slices.Values(imports)))

	shared := make(map[string]int, len(paths))
	for _, importPath := range paths {
		shared[path.Base(importPath)]++
	}
	// depth is the number of trailing path segments an import's name is built
	// from; depth 1 is its package name, which needs no alias.
	depth := make(map[string]int, len(paths))
	for _, importPath := range paths {
		depth[importPath] = 1
		if shared[path.Base(importPath)] > 1 {
			depth[importPath] = 2
		}
	}
	for {
		byName := make(map[string][]string, len(paths))
		for _, importPath := range paths {
			name := importName(importPath, depth[importPath])
			byName[name] = append(byName[name], importPath)
		}
		grown := false
		for _, clashing := range byName {
			if len(clashing) < 2 {
				continue
			}
			for _, importPath := range clashing {
				if depth[importPath] > 1 && depth[importPath] <= strings.Count(importPath, "/") {
					depth[importPath]++
					grown = true
				}
			}
		}
		if !grown {
			break
		}
	}

	aliases := make(map[string]string, len(paths))
	taken := make(map[string]bool, len(paths))
	for _, importPath := range paths {
		if depth[importPath] == 1 {
			aliases[importPath] = ""
			taken[importName(importPath, 1)] = true
		}
	}
	for _, importPath := range paths {
		if depth[importPath] == 1 {
			continue
		}
		name := importName(importPath, depth[importPath])
		alias := name
		for n := 2; taken[alias]; n++ {
			alias = name + strconv.Itoa(n)
		}
		aliases[importPath] = alias
		taken[alias] = true
	}
	return aliases
}

// importName joins the last depth segments of importPath with underscores, or
// all of them when it has fewer, into a Go identifier: every character an
// identifier cannot hold becomes an underscore, and a name that is still not
// one, because it starts with a digit or is a keyword, gets an underscore in
// front.
func importName(importPath string, depth int) string {
	segments := strings.Split(importPath, "/")
	name := strings.Map(func(r rune) rune {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			return r
		}
		return '_'
	}, strings.Join(segments[max(len(segments)-depth, 0):], "_"))
	if !token.IsIdentifier(name) {
		name = "_" + name
	}
	return name
}
