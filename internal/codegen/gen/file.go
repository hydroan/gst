// BuildRouterFile generates the router registration file, router.gen.go, in
// package pkgName with stmts ahead of the return statement of its Init
// function; gstModelPkg is the name the file imports the gst model package
// under, "" when no registration references it, and aliases maps each model
// package it imports to the alias RouterFileAliases picked for it. For the
// models Group and User of the root model package it generates
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package router
//
//	import (
//		"helloworld/model"
//
//		"github.com/hydroan/gst"
//		"github.com/hydroan/gst/consts"
//		"github.com/hydroan/gst/router"
//	)
//
//	func Init() error {
//		router.Register[*model.Group, *model.Group, *model.Group](router.Auth(), "groups", &gst.ControllerConfig[*model.Group]{}, consts.List)
//		router.Register[*model.User, *model.User, *model.User](router.Pub(), "users", &gst.ControllerConfig[*model.User]{}, consts.Create)
//		return nil
//	}
func BuildRouterFile(pkgName, gstModelPkg string, aliases map[string]string, stmts ...ast.Stmt) (string, error) {
	body := make([]ast.Stmt, 0, len(stmts)+1)
	body = append(body, stmts...)
	body = append(body, &ast.ReturnStmt{
		Results: []ast.Expr{
			ast.NewIdent("nil"),
		},
	})

	initDecl := &ast.FuncDecl{
		Name: ast.NewIdent(ggconst.FuncInit2),
		Type: &ast.FuncType{
			TypeParams: nil,
			Params:     nil,
			Results: &ast.FieldList{
				List: []*ast.Field{
					{Type: ast.NewIdent("error")},
				},
			},
		},
		Body: &ast.BlockStmt{
			List: body,
		},
	}

	// Every import after the lead ones is ordered by its entry: the import
	// path, or "gstmodel path" for the gst model package imported under the
	// gstmodel alias. Where the imports stand decides how the file groups
	// them: gofumpt lifts a project import without a dot in its path, which
	// it takes for a standard library one, to the top, and the imports on
	// either side of the gap it leaves become separate groups. Ordering by
	// the entry keeps that grouping as it has always been.
	entries := slices.Concat(slices.Collect(maps.Keys(aliases)), routerFileSortedImports)
	if gstModelPkg != "" {
		entries = append(entries, GstModelImportEntry(gstModelPkg))
	}
	slices.Sort(entries)
	importDecl := &ast.GenDecl{
		Tok:   token.IMPORT,
		Specs: importSpecs(routerFileLeadImports, nil),
	}
	for _, entry := range entries {
		alias, importPath, ok := strings.Cut(entry, " ")
		if !ok {
			alias, importPath = aliases[entry], entry
		}
		spec := &ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(importPath)}}
		if alias != "" {
			spec.Name = ast.NewIdent(alias)
		}
		importDecl.Specs = append(importDecl.Specs, spec)
	}

	f := &ast.File{
		Name:  ast.NewIdent(pkgName),
		Decls: []ast.Decl{
			// NOTE: imports must appear before other declarations
		},
	}

	// Create generated code comment at the top of the file
	generatedComment := &ast.CommentGroup{
		List: []*ast.Comment{
			{
				Text:  consts.CodeGeneratedComment(),
				Slash: token.Pos(1),
			},
		},
	}
	f.Comments = []*ast.CommentGroup{generatedComment}
	// Set package name position to ensure comment appears before it
	f.Name.NamePos = token.Pos(2)

	// Without stmts the Init function only returns nil, so the file imports
	// no package.
	if len(stmts) != 0 {
		// imports
		f.Decls = append(f.Decls, importDecl)
	}
	// Init() declarations.
	f.Decls = append(f.Decls, initDecl)

	return FormatNodeExtra(f, false)
}

// mainImportSpecs builds the imports of a generated main.go: every project
// package in ggconst.ProjectImportDirs, then the framework packages main
// calls into. The router package is the only project import with a name,
// because main calls router.Init; the others are linked for their
// initialisers alone.
func mainImportSpecs(projectName string) []ast.Spec {
	specs := make([]ast.Spec, 0, len(ggconst.ProjectImportDirs)+2)
	for _, dir := range ggconst.ProjectImportDirs {
		spec := &ast.ImportSpec{Path: &ast.BasicLit{Value: fmt.Sprintf("%q", projectName+"/"+dir)}}
		if dir != ggconst.DirRouter {
			spec.Name = ast.NewIdent("_")
		}
		specs = append(specs, spec)
	}
	return append(specs,
		&ast.ImportSpec{Path: &ast.BasicLit{Value: fmt.Sprintf("%q", ggconst.ImportPathBootstrap)}},
		&ast.ImportSpec{
			Path: &ast.BasicLit{Value: fmt.Sprintf("%q", ggconst.ImportPathUtil)},
			Name: ast.NewIdent("."),
		},
	)
}

// BuildMainFile generates the main.go file of the project at the module path
// projectName: for helloworld it generates
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package main
//
//	import (
//		_ "helloworld/component"
//		_ "helloworld/configx"
//		_ "helloworld/cronjob"
//		_ "helloworld/leader"
//		_ "helloworld/lock"
//		_ "helloworld/middleware"
//		_ "helloworld/model"
//		_ "helloworld/module"
//		"helloworld/router"
//		_ "helloworld/service"
//
//		"github.com/hydroan/gst/bootstrap"
//		. "github.com/hydroan/gst/util"
//	)
//
//	func main() {
//		RunOrDie(bootstrap.Bootstrap)
//		RunOrDie(router.Init)
//		RunOrDie(bootstrap.Run)
//	}
func BuildMainFile(projectName string) (string, error) {
	f := &ast.File{
		Name: ast.NewIdent(ggconst.PkgMain),
		Decls: []ast.Decl{
			&ast.GenDecl{
				Tok:   token.IMPORT,
				Specs: mainImportSpecs(projectName),
			},
			&ast.FuncDecl{
				Name: ast.NewIdent(ggconst.FuncMain),
				Type: &ast.FuncType{},
				Body: &ast.BlockStmt{
					List: []ast.Stmt{
						&ast.ExprStmt{
							X: &ast.CallExpr{
								Fun: ast.NewIdent(ggconst.FuncRunOrDie),
								Args: []ast.Expr{
									&ast.SelectorExpr{
										X:   ast.NewIdent(ggconst.PkgBootstrap),
										Sel: ast.NewIdent(ggconst.BootstrapBootstrap),
									},
								},
							},
						},
						&ast.ExprStmt{
							X: &ast.CallExpr{
								Fun: ast.NewIdent(ggconst.FuncRunOrDie),
								Args: []ast.Expr{
									&ast.SelectorExpr{
										X:   ast.NewIdent(ggconst.PkgRouter),
										Sel: ast.NewIdent(ggconst.RouterInit),
									},
								},
							},
						},
						&ast.ExprStmt{
							X: &ast.CallExpr{
								Fun: ast.NewIdent(ggconst.FuncRunOrDie),
								Args: []ast.Expr{
									&ast.SelectorExpr{
										X:   ast.NewIdent(ggconst.PkgBootstrap),
										Sel: ast.NewIdent(ggconst.BootstrapRun),
									},
								},
							},
						},
					},
				},
			},
		},
	}

	// Create generated code comment at the top of the file
	generatedComment := &ast.CommentGroup{
		List: []*ast.Comment{
			{
				Text:  consts.CodeGeneratedComment(),
				Slash: token.Pos(1),
			},
		},
	}
	f.Comments = []*ast.CommentGroup{generatedComment}
	// Set package name position to ensure comment appears before it
	f.Name.NamePos = token.Pos(2)

	return FormatNodeExtra(f, false)
}
