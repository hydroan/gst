`,
		},
		{
			// The example of the BuildRouterFile doc comment.
			name:    "registrations",
			pkgName: "router",
			aliases: map[string]string{"helloworld/model": ""},
			stmts: []ast.Stmt{
				gen.StmtRouterRegister("model", "Group", "*Group", "*Group", "model", "Auth", "groups", "", "List"),
				gen.StmtRouterRegister("model", "User", "*User", "*User", "model", "Pub", "users", "", "Create"),
			},
			want: `// Code generated by gst; DO NOT EDIT.

package router

import (
	"helloworld/model"

	"github.com/hydroan/gst"
	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/router"
)

func Init() error {
	router.Register[*model.Group, *model.Group, *model.Group](router.Auth(), "groups", &gst.ControllerConfig[*model.Group]{}, consts.List)
	router.Register[*model.User, *model.User, *model.User](router.Pub(), "users", &gst.ControllerConfig[*model.User]{}, consts.Create)
	return nil
}
`,
		},
		{
			name:    "module_sorting_before_the_framework",
			pkgName: "router",
			aliases: map[string]string{"demo/model": "", "demo/model/sample": ""},
			stmts:   []ast.Stmt{logPrintlnHelloWorld()},
			want: `// Code generated by gst; DO NOT EDIT.

