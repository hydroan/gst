func TestBuildModelFile(t *testing.T) {
	tests := []struct {
		name         string
		pkgName      string
		modelImports []string
		stmts        []ast.Stmt
		want         string
	}{
		{
			name:         "empty",
			pkgName:      "model",
			modelImports: []string{},
			stmts:        nil,
			want: `// Code generated by gst; DO NOT EDIT.

package model

func init() {
}
`,
		},
		{
			name:         "user",
			pkgName:      "model",
			modelImports: []string{},
			stmts:        []ast.Stmt{gen.StmtModelRegister("User")},
			want: `// Code generated by gst; DO NOT EDIT.

package model

import "github.com/hydroan/gst/model"

func init() {
	model.Register[*User]()
}
`,
		},
		{
			name:         "user_group",
			pkgName:      "model",
			modelImports: []string{"helloworld/model"},
			stmts: []ast.Stmt{
				gen.StmtModelRegister("User"),
				gen.StmtModelRegister("Group"),
			},
			want: `// Code generated by gst; DO NOT EDIT.

package model

import (
	"helloworld/model"

	"github.com/hydroan/gst/model"
)

func init() {
	model.Register[*User]()
	model.Register[*Group]()
}
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := gen.BuildModelFile(tt.pkgName, tt.modelImports, tt.stmts...)
			if err != nil {
				t.Fatalf("BuildModelFile() failed: %v", err)
			}
			if got != tt.want {
				t.Errorf("BuildModelFile() = \n%v\n, want \n%v\n", pretty.Sprintf("% #v", got), pretty.Sprintf("% #v", tt.want))
			}
		})
	}
}

func TestBuildServiceFile(t *testing.T) {
	tests := []struct {
		name         string
		pkgName      string
		modelImports []string
		stmts        []ast.Stmt
		want         string
	}{
		{
			name:         "empty",
			pkgName:      "service",
			modelImports: []string{},
			stmts:        nil,
			want: `// Code generated by gst; DO NOT EDIT.

package service

func init() {
}
`,
		},
		{
			name:         "user",
			pkgName:      "service",
			modelImports: []string{"helloworld/model"},
			stmts:        []ast.Stmt{gen.StmtServiceRegister("user", consts.PHASE_CREATE, "users")},
			want: `// Code generated by gst; DO NOT EDIT.

package service

import (
	"helloworld/model"

	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/service"
)

func init() {
	service.Register[*user](consts.PHASE_CREATE, "users")
}
`,
		},
		{
			name:         "user_group",
			pkgName:      "service",
			modelImports: []string{"helloworld/model"},
			stmts:        []ast.Stmt{gen.StmtServiceRegister("user", consts.PHASE_CREATE, "users"), gen.StmtServiceRegister("group", consts.PHASE_UPDATE, "groups/:id")},
			want: `// Code generated by gst; DO NOT EDIT.

package service

import (
	"helloworld/model"

	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/service"
)

func init() {
	service.Register[*user](consts.PHASE_CREATE, "users")
	service.Register[*group](consts.PHASE_UPDATE, "groups/:id")
}
`,
		},
		{
			name:         "conflicting_imports_get_distinct_aliases",
			pkgName:      "service",
			modelImports: []string{"helloworld/service/archive/record/item", "helloworld/service/sample/record/item"},
			stmts: []ast.Stmt{
				gen.StmtServiceRegister("archive_record_item.Creator", consts.PHASE_CREATE, "archive/record/items"),
				gen.StmtServiceRegister("sample_record_item.Creator", consts.PHASE_CREATE, "sample/record/items"),
			},
			want: `// Code generated by gst; DO NOT EDIT.

package service

import (
	archive_record_item "helloworld/service/archive/record/item"
	sample_record_item "helloworld/service/sample/record/item"

	"github.com/hydroan/gst/consts"
	"github.com/hydroan/gst/service"
)

func init() {
	service.Register[*archive_record_item.Creator](consts.PHASE_CREATE, "archive/record/items")
	service.Register[*sample_record_item.Creator](consts.PHASE_CREATE, "sample/record/items")
}
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := gen.BuildServiceFile(tt.pkgName, tt.modelImports, tt.stmts...)
			if err != nil {
				t.Fatalf("BuildServiceFile() failed: %v", err)
			}
			if got != tt.want {
				t.Errorf("BuildServiceFile() = \n%v\n, want \n%v\n", pretty.Sprintf("% #v", got), pretty.Sprintf("% #v", tt.want))
			}
		})
	}
}

