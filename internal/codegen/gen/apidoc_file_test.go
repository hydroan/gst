package gen_test

import (
	"strings"
	"testing"

	"github.com/hydroan/gst/apidoc"
	"github.com/hydroan/gst/internal/codegen/gen"
)

func TestBuildAPIDocFile(t *testing.T) {
	entries := gen.APIDocEntries{
		Structs: []gen.StructDocEntry{
			{
				PkgPath:  "example.com/proj/model",
				TypeName: "User",
				Doc: apidoc.StructDoc{
					Comment: "User is the user record.\nIt spans multiple lines.",
					Fields: map[string]string{
						"Name": "Name is the user name.",
						"Age":  "Age is the user age.",
					},
				},
			},
			{
				PkgPath:  "example.com/proj/model/sub",
				TypeName: "ArchiveReq",
				Doc: apidoc.StructDoc{
					Fields: map[string]string{"Path": "Path is the file path."},
				},
			},
		},
		Enums: []gen.EnumDocEntry{
			{
				PkgPath:  "example.com/proj/model",
				TypeName: "UserStatus",
				Doc: apidoc.EnumDoc{
					Comment: "UserStatus is the lifecycle status.",
					Values: []apidoc.EnumValue{
						{Value: "active", Comment: "the user can log in"},
						{Value: 2},
					},
				},
			},
		},
	}

	code, err := gen.BuildAPIDocFile("model", entries)
	if err != nil {
		t.Fatalf("BuildAPIDocFile() error = %v", err)
	}

	for _, want := range []string{
		"// Code generated by gst; DO NOT EDIT.",
		"package model",
		`import "github.com/hydroan/gst/apidoc"`,
		`apidoc.Register("example.com/proj/model", "User", apidoc.StructDoc{`,
		`Comment: "User is the user record.\nIt spans multiple lines.",`,
		`"Name": "Name is the user name.",`,
		`apidoc.Register("example.com/proj/model/sub", "ArchiveReq", apidoc.StructDoc{`,
		`apidoc.RegisterEnum("example.com/proj/model", "UserStatus", apidoc.EnumDoc{`,
		`Comment: "UserStatus is the lifecycle status.",`,
		`{Value: "active", Comment: "the user can log in"},`,
		`{Value: 2},`,
	} {
		if !strings.Contains(code, want) {
			t.Fatalf("BuildAPIDocFile() output missing %q, got:\n%s", want, code)
		}
	}
}

// TestBuildAPIDocFileRegistersStructsAndEnums compares the whole file
// BuildAPIDocFile generates for the example of its doc comment.
func TestBuildAPIDocFileRegistersStructsAndEnums(t *testing.T) {
	code, err := gen.BuildAPIDocFile("model", gen.APIDocEntries{
		Structs: []gen.StructDocEntry{{
			PkgPath:  "helloworld/model",
			TypeName: "User",
			Doc: apidoc.StructDoc{
				Comment: "User is the user record.",
				Fields:  map[string]string{"Name": "Name is the user name."},
			},
		}},
		Enums: []gen.EnumDocEntry{{
			PkgPath:  "helloworld/model",
			TypeName: "UserRole",
			Doc: apidoc.EnumDoc{
				Comment: "UserRole grades what a user may do.",
				Values: []apidoc.EnumValue{
					{Value: "owner", Comment: "UserRoleOwner manages the project."},
					{Value: "member"},
				},
			},
		}},
	})
	if err != nil {
		t.Fatalf("BuildAPIDocFile() error = %v", err)
	}
	want := `// Code generated by gst; DO NOT EDIT.

package model

import "github.com/hydroan/gst/apidoc"

func init() {
	apidoc.Register("helloworld/model", "User", apidoc.StructDoc{
		Comment: "User is the user record.",
		Fields: map[string]string{
			"Name": "Name is the user name.",
		},
	})
	apidoc.RegisterEnum("helloworld/model", "UserRole", apidoc.EnumDoc{
		Comment: "UserRole grades what a user may do.",
		Values: []apidoc.EnumValue{
			{Value: "owner", Comment: "UserRoleOwner manages the project."},
			{Value: "member"},
		},
	})
}
`
	if code != want {
		t.Errorf("BuildAPIDocFile() =\n%s\nwant\n%s", code, want)
	}
}

func TestBuildAPIDocFileWithoutEntries(t *testing.T) {
	code, err := gen.BuildAPIDocFile("model", gen.APIDocEntries{})
	if err != nil {
		t.Fatalf("BuildAPIDocFile() error = %v", err)
	}

	if strings.Contains(code, "import") {
		t.Fatalf("BuildAPIDocFile() output should not import packages when there are no entries, got:\n%s", code)
	}
	if !strings.Contains(code, "func init()") {
		t.Fatalf("BuildAPIDocFile() output missing init function, got:\n%s", code)
	}
}
