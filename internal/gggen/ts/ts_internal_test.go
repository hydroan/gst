// TestGenerateMatchesGoldenFiles holds the files generated from Sample and
// the routes of sampleRoutes against testdata/golden; run it with -update to
// rewrite them. The golden files carry the examples of the Generate, render,
// writeInterface, property, propertyDoc, expr, ref, builtin, structural,
// value, files, enumBody, enumZero, constantLiteral and exchange doc
// comments.
func TestGenerateMatchesGoldenFiles(t *testing.T) {
	files, err := generateRouted(t)
	require.NoError(t, err)

	golden := filepath.Join("testdata", "golden")
	if *update {
		require.NoError(t, os.RemoveAll(golden))
		writeFiles(t, golden, files)
	}
	got := make(map[string]string, len(files))
	for _, f := range files {
		got[f.Path] = f.Content
	}
	require.Equal(t, readFiles(t, golden), got)
}

// TestGenerateWritesTheRouteTable holds the route table of three routes
// against the file it is written as, the example of the routeTable doc
// comment: a list the framework serves, with its query and the list data in
// the envelope; a delete the framework serves, its parameter in the path and
// no data in the envelope; and an action exchanging types of its own, both
// parameters of its path, its request body and its response.
func TestGenerateWritesTheRouteTable(t *testing.T) {
	cfg := fixtureConfig(sampleRoot)
	cfg.Routes = []Route{
		{Path: "/api/samples", Phase: apiaction.List, Payload: sampleRoot, Result: sampleRoot},
		{Path: "/api/samples/:id", Phase: apiaction.Delete, Payload: sampleRoot, Result: sampleRoot},
		{Path: "/api/samples/:id/items/:item", Phase: apiaction.Update, Payload: itemRoot, Result: recordRoot, Custom: true},
	}
	files, err := newGenerator(cfg, loadFixture(t)).generate()
	require.NoError(t, err)

	at := slices.IndexFunc(files, func(f File) bool { return f.Path == "paths.ts" })
	require.GreaterOrEqual(t, at, 0, "the run writes paths.ts")
	require.Equal(t, `// Code generated by gst; DO NOT EDIT.

import type { Envelope, ErrorEnvelope, ListResult } from "./gst.js";
import type * as $record from "./record.js";
import type * as $sample from "./sample.js";

/**
 * paths maps every route the models declare to what each of its methods
 * takes and answers: the parameters of the path and of the query, the JSON
 * body of the request, and the body of the response, the envelope of the 200
 * a success answers and the one of every failure. It is laid out the way
 * openapi-typescript lays out the paths of an OpenAPI document, so a client
 * typed by such a table takes it as it is.
 */
export interface paths {
  "/api/samples": {
    get: {
      parameters: { query?: { [name: string]: string | number | boolean } };
      responses: {
        200: { content: { "application/json": Envelope<ListResult<$sample.Sample>> } };
        default: { content: { "application/json": ErrorEnvelope } };
      };
    };
  };
  "/api/samples/{id}": {
    delete: {
      parameters: { path: { id: string } };
      responses: {
        200: { content: { "application/json": Envelope<null> } };
        default: { content: { "application/json": ErrorEnvelope } };
      };
    };
  };
  "/api/samples/{id}/items/{item}": {
    put: {
      parameters: { path: { id: string; item: string } };
      requestBody: { content: { "application/json": $sample.Item } };
      responses: {
        200: { content: { "application/json": Envelope<$record.Record> } };
        default: { content: { "application/json": ErrorEnvelope } };
      };
    };
  };
}
`, files[at].Content)
}

// TestGenerateWritesNoRouteTableWithoutRoutes pins that a run given no route
// writes no route table: the table of nothing would be a file to keep in
