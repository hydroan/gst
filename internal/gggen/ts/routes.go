// This file holds the route table: the file listing, for every route a run
// is given, what its method takes and answers.

// Route is one action of a model on the path it is served at, for the route
// table (see Config.Routes).
type Route struct {
	// Path is the path the router registers the action at, parameters
	// written :name, as /api/samples/:id.
	Path string
	// Phase is the action, one a JSON request is sent to and answered:
	// Create, Delete, Update, Patch, List, Get or one of their batch forms.
	// It names the method of the route (see apiaction.Phase.HTTPMethod).
	Phase apiaction.Phase
	// Payload and Result are the request and the response type of the
	// action, the zero TypeRef for one that carries no data.
	Payload, Result TypeRef
	// Custom tells an action exchanging types of its own, which travel as
	// they are, from one the framework serves for the model itself, whose
	// request and response take the shape of its action: the list data of a
	// List, the items of a batch, no data for a delete.
	Custom bool
}

// The file the route table goes to and the interface it declares, named the
// way openapi-typescript names the table of an OpenAPI document.
const (
	routeTableFile = "paths.ts"
	routeTableName = "paths"
)

// routeTableDoc is the doc comment of the route table.
const routeTableDoc = `paths maps every route the models declare to what each of its methods
takes and answers: the parameters of the path and of the query, the JSON
body of the request, and the body of the response, the envelope of the 200
a success answers and the one of every failure. It is laid out the way
openapi-typescript lays out the paths of an OpenAPI document, so a client
typed by such a table takes it as it is.`

// routeMethods are the methods of the routes the table lists, in the order a
// path lists them.
var routeMethods = []string{http.MethodGet, http.MethodPost, http.MethodPut, http.MethodPatch, http.MethodDelete}

// The types of the prelude the table wraps the types of the routes in.
const (
	preludeEnvelope      = "Envelope"
	preludeErrorEnvelope = "ErrorEnvelope"
	preludeListResult    = "ListResult"
	preludeItemsPayload  = "ItemsPayload"
	preludeIDsPayload    = "IDsPayload"
)

// routeTable renders the route table of the run's routes into the file
// paths.ts: an interface keyed by path, parameters in braces, then by method,
// in the order of routeMethods, each method with the parameters of its path,
// the query of a List, its request body when it reads one, and its
// responses. The types of the routes are referred to through the namespace
// imports the other files use, and the shapes the framework wraps them in
// are imported from the prelude by name. ok is false for a run without
// routes, which writes no table. owners names what takes each output file
// already and aliases the package each import name stands for, both as files
// keeps them.
//
// For the routes
//
//	{Path: "/api/samples", Phase: apiaction.List, Payload: Sample, Result: Sample}
//	{Path: "/api/samples/:id", Phase: apiaction.Delete, Payload: Sample, Result: Sample}
//	{Path: "/api/samples/:id/items/:item", Phase: apiaction.Update, Payload: Item, Result: Record, Custom: true}
//
// with Sample and Item of package sample and Record of package record, the
// file is
//
//	// Code generated by gst; DO NOT EDIT.
//
//	import type { Envelope, ErrorEnvelope, ListResult } from "./gst.js";
//	import type * as $record from "./record.js";
//	import type * as $sample from "./sample.js";
//
//	/**
//	 * paths maps every route the models declare to what each of its methods
//	 * takes and answers: the parameters of the path and of the query, the JSON
//	 * body of the request, and the body of the response, the envelope of the 200
//	 * a success answers and the one of every failure. It is laid out the way
//	 * openapi-typescript lays out the paths of an OpenAPI document, so a client
//	 * typed by such a table takes it as it is.
//	 */
//	export interface paths {
//	  "/api/samples": {
//	    get: {
//	      parameters: { query?: { [name: string]: string | number | boolean } };
//	      responses: {
//	        200: { content: { "application/json": Envelope<ListResult<$sample.Sample>> } };
//	        default: { content: { "application/json": ErrorEnvelope } };
//	      };
//	    };
//	  };
//	  "/api/samples/{id}": {
//	    delete: {
//	      parameters: { path: { id: string } };
//	      responses: {
//	        200: { content: { "application/json": Envelope<null> } };
//	        default: { content: { "application/json": ErrorEnvelope } };
//	      };
//	    };
//	  };
//	  "/api/samples/{id}/items/{item}": {
//	    put: {
//	      parameters: { path: { id: string; item: string } };
//	      requestBody: { content: { "application/json": $sample.Item } };
//	      responses: {
//	        200: { content: { "application/json": Envelope<$record.Record> } };
//	        default: { content: { "application/json": ErrorEnvelope } };
//	      };
//	    };
//	  };
//	}
func (g *generator) routeTable(owners, aliases map[string]string) (file File, ok bool) {
	if len(g.cfg.Routes) == 0 {
		return File{}, false
	}
	if owner, taken := owners[routeTableFile]; taken {
		g.project.Report(jsonshape.Site{Subject: routeTableFile}, "the route table is written to %s, which %s takes already; rename what takes it", routeTableFile, owner)
		return File{}, false
	}
	owners[routeTableFile] = "the route table"

	ctx := &fileContext{imports: make(map[string]bool)}
	prelude := map[string]bool{preludeEnvelope: true, preludeErrorEnvelope: true}
	operations := make(map[string]map[string]string)
	for _, route := range g.cfg.Routes {
		method := route.Phase.HTTPMethod()
		path, params := tablePath(route.Path)
		if _, taken := operations[path][method]; taken {
			g.project.Report(jsonshape.Site{Subject: path}, "%s %s is served by two actions, and the route table lists one for a method of a path", method, path)
			continue
		}
		body, data, wraps, covered := g.exchange(route, ctx)
		if !covered {
			g.project.Report(jsonshape.Site{Subject: path}, "the route table has no entry for the %s action, which exchanges no JSON request and response", route.Phase.Name())
			continue
		}
		for _, wrap := range wraps {
			prelude[wrap] = true
		}

		var b strings.Builder
		var parameters []string
		if len(params) > 0 {
			named := make([]string, 0, len(params))
			for _, param := range params {
				named = append(named, propertyName(param)+": string")
			}
			parameters = append(parameters, "path: { "+strings.Join(named, "; ")+" }")
		}
		if route.Phase == apiaction.List {
			parameters = append(parameters, "query?: { [name: string]: string | number | boolean }")
		}
		if len(parameters) > 0 {
			fmt.Fprintf(&b, "      parameters: { %s };\n", strings.Join(parameters, "; "))
		}
		if body != "" {
			fmt.Fprintf(&b, "      requestBody: { content: { \"application/json\": %s } };\n", body)
		}
		b.WriteString("      responses: {\n")
		fmt.Fprintf(&b, "        200: { content: { \"application/json\": %s<%s> } };\n", preludeEnvelope, data)
		fmt.Fprintf(&b, "        default: { content: { \"application/json\": %s } };\n", preludeErrorEnvelope)
		b.WriteString("      };\n")
		if operations[path] == nil {
			operations[path] = make(map[string]string)
		}
		operations[path][method] = b.String()
	}

	var b strings.Builder
	b.WriteString(ggconst.CodeGeneratedComment)
	b.WriteString("\n\n")
	fmt.Fprintf(&b, "import type { %s } from %s;\n", strings.Join(slices.Sorted(maps.Keys(prelude)), ", "), quoteString(relativeImport(routeTableFile, g.preludeFile)))
	for _, imported := range slices.Sorted(maps.Keys(ctx.imports)) {
		alias := g.importAlias(imported)
		if other, clash := aliases[alias]; clash && other != imported {
			g.project.Report(jsonshape.Site{Subject: imported}, "the package and %s are both imported as %s; rename one of them", other, alias)
		}
		aliases[alias] = imported
		fmt.Fprintf(&b, "import type * as %s from %s;\n", alias, quoteString(relativeImport(routeTableFile, g.filePath(imported))))
	}
	b.WriteString("\n")
	writeDoc(&b, "", routeTableDoc)
	fmt.Fprintf(&b, "export interface %s {\n", routeTableName)
	for _, path := range slices.Sorted(maps.Keys(operations)) {
		fmt.Fprintf(&b, "  %s: {\n", quoteString(path))
		for _, method := range routeMethods {
			if operation, served := operations[path][method]; served {
				fmt.Fprintf(&b, "    %s: {\n%s    };\n", strings.ToLower(method), operation)
			}
		}
		b.WriteString("  };\n")
	}
	b.WriteString("}\n")
	return File{Path: routeTableFile, Content: b.String()}, true
}

// tablePath returns the path of a route the way the table keys it, each
// parameter in braces, /api/samples/{id}/items/{item} for
// /api/samples/:id/items/:item, and the names of the parameters in the order
// the path carries them, id and item.
func tablePath(route string) (path string, params []string) {
	segments := strings.Split(route, "/")
	for i, segment := range segments {
		if name, isParam := strings.CutPrefix(segment, ":"); isParam && name != "" {
			segments[i] = "{" + name + "}"
			params = append(params, name)
		}
	}
	return strings.Join(segments, "/"), params
}

// exchange returns what the action of route reads as its JSON body, empty
// for an action reading none, and the data its envelope answers with, as
// TypeScript types referring to the declarations of the route's types from
// the file of ctx, with the prelude types they are wrapped in. covered is
// false for an action the table has no entry for.
//
// An action exchanging types of its own (see Route.Custom) sends and answers
// them as they are, null for a result carrying no data. The table gives a List,
// a Get and a Delete no body: a List and a Get read none, and the body a Delete
// of its own types reads is left out the way the API document leaves it out. An
// action the framework serves for the model takes the shape of its action, with
// Sample the model:
//
//	Create, Update:          Sample                        -> Sample
//	Patch:                   Partial<Sample>               -> Sample
//	Get:                     no body                       -> Sample
//	List:                    no body                       -> ListResult<Sample>
//	Delete:                  no body                       -> null
//	CreateMany, UpdateMany:  ItemsPayload<Sample>          -> ItemsPayload<Sample>
//	PatchMany:               ItemsPayload<Partial<Sample>> -> ItemsPayload<Sample>
//	DeleteMany:              IDsPayload                    -> null
func (g *generator) exchange(route Route, ctx *fileContext) (body, data string, wraps []string, covered bool) {
	payload, result := g.routeType(route.Payload, ctx), g.routeType(route.Result, ctx)
	if route.Custom {
		switch route.Phase {
		case apiaction.List, apiaction.Get, apiaction.Delete:
			payload = ""
		case apiaction.Create, apiaction.Update, apiaction.Patch, apiaction.CreateMany, apiaction.UpdateMany, apiaction.PatchMany, apiaction.DeleteMany:
		default:
			return "", "", nil, false
		}
		if result == "" {
			result = "null"
		}
		return payload, result, nil, true
	}
	items := preludeItemsPayload + "<" + result + ">"
	switch route.Phase {
	case apiaction.Create, apiaction.Update:
		return payload, result, nil, true
	case apiaction.Patch:
		return "Partial<" + payload + ">", result, nil, true
	case apiaction.Get:
		return "", result, nil, true
	case apiaction.List:
		return "", preludeListResult + "<" + result + ">", []string{preludeListResult}, true
	case apiaction.Delete:
		return "", "null", nil, true
	case apiaction.CreateMany, apiaction.UpdateMany:
		return preludeItemsPayload + "<" + payload + ">", items, []string{preludeItemsPayload}, true
	case apiaction.PatchMany:
		return preludeItemsPayload + "<Partial<" + payload + ">>", items, []string{preludeItemsPayload}, true
	case apiaction.DeleteMany:
		return preludeIDsPayload, "null", []string{preludeIDsPayload}, true
	}
	return "", "", nil, false
}

// routeType renders a reference to the declaration of a route's type from
// the file of ctx, $sample.Sample, and nothing for the zero TypeRef or for a
// type the run found no declaration of, which declareRoot reported.
func (g *generator) routeType(ref TypeRef, ctx *fileContext) string {
	if ref == (TypeRef{}) {
		return ""
	}
	pkg := g.project.Package(ref.PkgPath)
	if pkg == nil || pkg.Types == nil {
		return ""
	}
	obj, declared := pkg.Types.Scope().Lookup(ref.Name).(*types.TypeName)
	if !declared {
		return ""
	}
	return g.ref(obj, ctx)
}
