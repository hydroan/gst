// TestPluginVersionsMatchTheFramework keeps the two protobuf plugins Compile
// runs at the versions the framework's go.mod requires of the modules
// providing them, the same way gg lint pins golangci-lint: the plugins are
// tools of the framework module, so upgrading one without the other fails
// here, and the Go files a project generates match the protobuf and grpc
// runtimes it gets through the framework.
func TestPluginVersionsMatchTheFramework(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "..", "..", "go.mod"))
	require.NoError(t, err)
	file, err := modfile.Parse("go.mod", data, nil)
	require.NoError(t, err)

	for _, plugin := range []struct{ pkg, version string }{
		{protocGenGoPackage, protocGenGoVersion},
		{protocGenGoGRPCPackage, protocGenGoGRPCVersion},
	} {
		// The module providing a package is the required one with the
		// longest path the package path starts with.
		packagePath := plugin.pkg + "/"
		var provider *modfile.Require
		for _, req := range file.Require {
			if strings.HasPrefix(packagePath, req.Mod.Path+"/") &&
				(provider == nil || len(req.Mod.Path) > len(provider.Mod.Path)) {
				provider = req
			}
		}
		require.NotNil(t, provider, "go.mod requires no module providing %s", plugin.pkg)
		require.Equal(t, plugin.version, provider.Mod.Version, "%s", plugin.pkg)
	}
}

// TestCompileWritesTheGoFilesOfTheDefinitions pins what Compile makes of the
// .proto files: beside pb/sample.proto, pb/sample.pb.go with its messages,
// carrying their comments, and pb/sample_grpc.pb.go with its service; beside
// pb/record/item.proto, which declares no service, pb/record/item.pb.go
// alone, in the Go package its go_package names.
func TestCompileWritesTheGoFilesOfTheDefinitions(t *testing.T) {
	got, err := Compile([]File{
		{Path: "pb/sample.proto", Content: `syntax = "proto3";

package tmpapp;

import "google/protobuf/timestamp.proto";

option go_package = "tmpapp/pb;pb";

// Sample is a record kept for the test.
message Sample {
  string id = 1;

  google.protobuf.Timestamp created_at = 2;
}

message GetSampleRequest {
  string id = 1;
}

message GetSampleResponse {
  Sample sample = 1;
}

service SampleService {
  rpc GetSample ( GetSampleRequest ) returns ( GetSampleResponse );
}
`},
		{Path: "pb/record/item.proto", Content: `syntax = "proto3";

package tmpapp.record;

option go_package = "tmpapp/pb/record;record";

message Item {
  string id = 1;
}
`},
	})
	require.NoError(t, err)

	paths := make([]string, 0, len(got))
	contents := make(map[string]string, len(got))
	for _, f := range got {
		paths = append(paths, f.Path)
		contents[f.Path] = f.Content
	}
	require.Equal(t, []string{"pb/record/item.pb.go", "pb/sample.pb.go", "pb/sample_grpc.pb.go"}, paths)
	require.Contains(t, contents["pb/sample.pb.go"], "// Code generated by protoc-gen-go. DO NOT EDIT.")
	require.Contains(t, contents["pb/sample.pb.go"], "\npackage pb\n")
	require.Contains(t, contents["pb/sample.pb.go"], "// Sample is a record kept for the test.\ntype Sample struct {")
	require.Contains(t, contents["pb/sample_grpc.pb.go"], "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.")
	require.Contains(t, contents["pb/sample_grpc.pb.go"], "type SampleServiceServer interface {")
	require.Contains(t, contents["pb/record/item.pb.go"], "\npackage record\n")
	require.Contains(t, contents["pb/record/item.pb.go"], "type Item struct {")
}

// TestCompileReportsWhatTheCompilerRefuses pins that a definition the
// protobuf compiler refuses fails Compile with the file and the problem
// named, and no Go file comes back.
func TestCompileReportsWhatTheCompilerRefuses(t *testing.T) {
	got, err := Compile([]File{{Path: "pb/sample.proto", Content: `syntax = "proto3";

package tmpapp;

option go_package = "tmpapp/pb;pb";

message Sample {
  Missing missing = 1;
}
`}})

	require.Nil(t, got)
	require.ErrorContains(t, err, "sample.proto")
	require.ErrorContains(t, err, "Missing")
}

// TestRunPluginRunsWithoutTheNetwork pins that the plugins run from the
// module cache alone once they are in it: with the module proxy switched
// off, an empty request still gets its empty answer from protoc-gen-go and
// protoc-gen-go-grpc alike. go run pkg@version would ask the proxy about
// the module first and fail here.
func TestRunPluginRunsWithoutTheNetwork(t *testing.T) {
	t.Setenv("GOPROXY", "off")
	for _, plugin := range []struct{ module, version, pkg string }{
		{protocGenGoModule, protocGenGoVersion, protocGenGoPackage},
		{protocGenGoGRPCModule, protocGenGoGRPCVersion, protocGenGoGRPCPackage},
	} {
		files, err := runPlugin(plugin.module, plugin.version, plugin.pkg, &pluginpb.CodeGeneratorRequest{})
		require.NoError(t, err, plugin.pkg)
		require.Empty(t, files)
	}
}
