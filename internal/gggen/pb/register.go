// This file builds the pb.gen.go of every package under pb/, the files
// registering the services on the listener.

// httpMethodConsts names the net/http constant of each HTTP method the
// registration describes an rpc by.
var httpMethodConsts = map[string]string{
	http.MethodGet:    "MethodGet",
	http.MethodPost:   "MethodPost",
	http.MethodPut:    "MethodPut",
	http.MethodPatch:  "MethodPatch",
	http.MethodDelete: "MethodDelete",
}

// registrationFiles builds the pb.gen.go of every package holding a
// definition, which registers the package's services on the listener at
// package initialization, the way router/router.gen.go registers the
// routes: one grpc.Register call per service, definition by definition,
// handing over the registration function the protobuf plugin generated and
// the type serving the service (see serviceType) under the server interface
// the plugin generated, and describing each rpc by its full method name,
// the constant the plugin generated for it, the HTTP method and route the
// same action is served at, which the interceptors of the modules judge a
// call by, and whether its action declares Public(). Every package
// registers its own services through the type serving each (see
// serviceTypeName), the way a package the protobuf plugin generates
// registers its own descriptors; the root pb/pb.gen.go, the file main.go
// imports, also imports every package below it for its registrations, and
// is written with nothing but those imports when no definition sits at the
// root.
//
// The golden fixture, whose Note and Record models are declared in model/
// and whose Item model in model/record/, gets pb/pb.gen.go, the Feed, Pin,
// Report and Shape services left out,
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package pb
//
//	import (
//		"net/http"
//		_ "tmpapp/pb/record"
//
//		"github.com/hydroan/gst/grpc"
//	)
//
//	func init() {
//		grpc.Register[NoteServiceServer](RegisterNoteServiceServer, noteService{},
//			grpc.Method{Name: NoteService_CreateNote_FullMethodName, HTTPMethod: http.MethodPost, Route: "/api/notes"},
//			grpc.Method{Name: NoteService_GetNote_FullMethodName, HTTPMethod: http.MethodGet, Route: "/api/notes/:id"},
//		)
//		grpc.Register[RecordServiceServer](RegisterRecordServiceServer, recordService{},
//			grpc.Method{Name: RecordService_CreateRecord_FullMethodName, HTTPMethod: http.MethodPost, Route: "/api/records"},
//			grpc.Method{Name: RecordService_DeleteRecord_FullMethodName, HTTPMethod: http.MethodDelete, Route: "/api/records/:record"},
//			...
//			grpc.Method{Name: RecordService_ListRecordByOwner_FullMethodName, HTTPMethod: http.MethodGet, Route: "/api/owners/:owner/records"},
//		)
