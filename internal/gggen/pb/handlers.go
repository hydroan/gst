// This file builds the Go file generated beside every definition: for each
// service the definition declares, the type serving it, the calls of its
// actions and the handlers of its rpcs, then the conversions of the
// definition's messages (see convert.go).

// handlerFile builds the Go file generated beside the definition f, named
// after it with the .gen.go suffix, pb/record.gen.go for pb/record.proto, in
// the package the definition's go_package names. For every service f
// declares it holds the type serving the service (see serviceType), the
// calls of the actions the rpcs run (see actionCalls) and one handler per
// rpc (see handler); then, for every project type f gives a message, the
// two conversion functions (see conversionFuncs).
//
// The definition report.proto of the golden fixture, whose Report model
// declares GRPC() and one custom Get on reports/summary answering with a
// ReportRsp, gets pb/report.gen.go (the module tmpapp of the fixture has no
// dot in its path, so the formatter groups its imports with the standard
// library's):
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package pb
//
//	import (
//		"context"
//		"tmpapp/model"
//
//		"github.com/hydroan/gst/consts"
//		"github.com/hydroan/gst/grpc"
//		gstmodel "github.com/hydroan/gst/model"
//	)
//
//	// ReportService serves the rpcs of the ReportService service through the
//	// actions of Report: every handler decodes its request message into what the
//	// action's call takes, runs the call and encodes what it answers into the
//	// response message.
//	type ReportService struct {
//		UnimplementedReportServiceServer
//	}
//
//	// The calls of the actions of Report, one per rpc of ReportService, built
//	// once at package initialization.
//	var getReport = grpc.ServiceCall[*model.Report, *gstmodel.Empty, *model.ReportRsp](consts.PHASE_GET, "reports/summary")
//
//	// GetReport serves the Get action of Report on reports/summary.
//	func (ReportService) GetReport(ctx context.Context, req *GetReportRequest) (*GetReportResponse, error) {
//		result, err := getReport(ctx, nil, grpc.Query{Expand: req.GetExpand(), Depth: req.GetDepth()}, new(gstmodel.Empty))
//		if err != nil {
//			return nil, err
//		}
//		return &GetReportResponse{Result: ReportRspToProto(result)}, nil
//	}
//
//	// ReportRspToProto encodes ReportRsp values into their message, nil into
//	// nil.
//	func ReportRspToProto(m *model.ReportRsp) *ReportRsp {
//		if m == nil {
//			return nil
//		}
//		p := new(ReportRsp)
//		p.Total = m.Total
//		return p
//	}
//
//	// ReportRspFromProto decodes ReportRsp messages into values, nil into nil.
//	func ReportRspFromProto(p *ReportRsp) *model.ReportRsp {
//		if p == nil {
//			return nil
//		}
//		m := new(model.ReportRsp)
//		m.Total = p.GetTotal()
//		return m
//	}
func (g *generator) handlerFile(f *protoFile) (File, error) {
	w := g.newFileWriter(f)
	var services []string
	rpcs := make(map[string][]*rpc)
	for _, r := range f.rpcs {
		if _, seen := rpcs[r.service]; !seen {
			services = append(services, r.service)
		}
		rpcs[r.service] = append(rpcs[r.service], r)
	}
	for _, service := range services {
		w.serviceType(service, rpcs[service][0].model)
		w.actionCalls(service, rpcs[service])
		for _, r := range rpcs[service] {
			w.handler(r)
		}
	}
	for _, msg := range f.typed {
		w.conversionFuncs(msg)
	}
	name := strings.TrimSuffix(f.name, ".proto") + ggconst.SuffixGenGo
	source, err := w.out.source()
	if err != nil {
		return File{}, errors.Wrapf(err, "print %s", name)
	}
	return File{Path: ggconst.DirPB + "/" + name, Content: source}, nil
}

// serviceType declares the type serving service, the service of model: it
// embeds the Unimplemented server the protobuf plugin generated, which
// answers Unimplemented for any rpc added later, and the handlers are its
// methods (see handler).
//
//	// RecordService serves the rpcs of the RecordService service through the
//	// actions of Record: every handler decodes its request message into what the
//	// action's call takes, runs the call and encodes what it answers into the
//	// response message.
//	type RecordService struct {
//		UnimplementedRecordServiceServer
//	}
func (w *fileWriter) serviceType(service string, model *modelinfo.Model) {
	w.out.add(service+" serves the rpcs of the "+service+" service through the actions of "+model.ModelName+
		": every handler decodes its request message into what the action's call takes, runs the call and encodes what it answers into the response message.",
		&ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{&ast.TypeSpec{
			Name: ident(service),
			Type: &ast.StructType{Fields: &ast.FieldList{List: []*ast.Field{{Type: ident("Unimplemented" + service + "Server")}}}},
		}}}, nil)
}

// actionCalls declares the calls of the actions the rpcs of service run,
// one variable per rpc named after it, built once at package initialization
// through the call functions of the framework's grpc package: the call of
// the model's standard action, CreateCall and its kind, on the route the
// router registers the action under, or ServiceCall for an action with a
// payload or result of its own, on its phase and route.
//
// The Item model of the golden fixture, with its two standard actions on
// records/:record/items, a Filename("seal") Create on items/:id/seal and a
// Filename("merge") Create on items/merge taking a MergeReq and answering a
// MergedItemRsp, gets
//
//	// The calls of the actions of Item, one per rpc of ItemService, built once
//	// at package initialization.
//	var (
//		createItem = grpc.CreateCall[*record.Item]("records/:record/items")
//		getItem    = grpc.GetCall[*record.Item]("records/:record/items/:id")
//		sealItem   = grpc.CreateCall[*record.Item]("items/:id/seal")
//		mergeItem  = grpc.ServiceCall[*record.Item, *record.MergeReq, *record.MergedItemRsp](consts.PHASE_CREATE, "items/merge")
//	)
func (w *fileWriter) actionCalls(service string, rpcs []*rpc) {
	model := rpcs[0].model
	specs := make([]ast.Spec, 0, len(rpcs))
	for _, r := range rpcs {
		modelType := star(w.modelPkgType(model, model.ModelName))
		var value ast.Expr
		if r.standard {
			value = call(index(w.grpc(r.action.Phase.MethodName()+"Call"), modelType), strLit(r.registered))
		} else {
			value = call(
				&ast.IndexListExpr{X: w.grpc("ServiceCall"), Indices: []ast.Expr{modelType, w.actionType(model, r.action.Payload), w.actionType(model, r.action.Result)}},
				sel(w.out.imports.fixedRef(ggconst.ImportPathConsts), "PHASE_"+strings.ToUpper(string(r.action.Phase))),
				strLit(r.registered),
			)
		}
		specs = append(specs, &ast.ValueSpec{Names: []*ast.Ident{ident(callName(r))}, Values: []ast.Expr{value}})
	}
	w.out.add("The calls of the actions of "+model.ModelName+", one per rpc of "+service+", built once at package initialization.",
		&ast.GenDecl{Tok: token.VAR, Specs: specs}, nil)
}

// callName names the variable holding the call of the rpc r: createRecord
// for CreateRecord.
func callName(r *rpc) string { return lowerFirst(r.name) }

// modelPkgType refers to the type typeName of the package of model.
func (w *fileWriter) modelPkgType(model *modelinfo.Model, typeName string) ast.Expr {
	return sel(w.out.imports.ref(model.ImportPath(), model.ModelPkgName), typeName)
}

// actionType spells the Payload or Result type of an action of model as
// ServiceCall takes it: the type as declared, *record.MergeReq for
// Payload[*MergeReq], and the framework's *gstmodel.Empty for a side the
// action does not declare.
func (w *fileWriter) actionType(model *modelinfo.Model, typeName string) ast.Expr {
	if typeName == "" || typeName == dsl.PayloadEmpty {
		return star(sel(w.out.imports.fixedRef(ggconst.ImportPathModel), "Empty"))
	}
	name, pointer := strings.CutPrefix(typeName, "*")
	if pointer {
		return star(w.modelPkgType(model, name))
	}
	return w.modelPkgType(model, name)
}

// handler builds the handler of the rpc r, a method of the type serving its
// service: it reads the route parameters, the id, the query, the record or
// the items and the update masks off the request message, runs the call of
// the action on them and answers the response message holding what the
// call answered.
//
// The rpcs of the Record model of the golden fixture on records, with the
// parameter record, get, among others,
//
//	// CreateRecord serves the Create action of Record on records.
//	func (RecordService) CreateRecord(ctx context.Context, req *CreateRecordRequest) (*CreateRecordResponse, error) {
