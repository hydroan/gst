func (w *fileWriter) handler(r *rpc) {
	w.resetTemps()
	requestFields, responseFields := goFieldNames(r.request), goFieldNames(r.response)
	req := func(name string) ast.Expr { return call(sel(ident("req"), "Get"+requestFields[name])) }
	callee := ident(callName(r))
	failing := func() ast.Stmt { return ifNotNil(ident("err"), returns(ident("nil"), ident("err"))) }
	respond := func(elts ...ast.Expr) ast.Stmt {
		return returns(addr(compositeLit(ident(r.response.GetName()), elts...)), ident("nil"))
	}
	run := func(args ...ast.Expr) ast.Expr { return call(callee, append([]ast.Expr{ident("ctx")}, args...)...) }
	// params are the route parameters the message carries, keyed as the
	// route names them; id is the one naming the record of an item action.
	params := ast.Expr(ident("nil"))
	var id ast.Expr
	if len(r.params) > 0 {
		lit := compositeLit(&ast.MapType{Key: ident("string"), Value: ident("string")})
		for _, p := range r.params {
			lit.Elts = append(lit.Elts, &ast.KeyValueExpr{Key: strLit(p.param), Value: req(p.name)})
			if p.param == r.param {
				id = req(p.name)
			}
		}
		params = lit
	}
	query, layout := w.query(r.action.Phase, req)

	var body []ast.Stmt
	if r.standard {
		x := modelFieldName(r.model)
		fromProto := func(message ast.Expr) ast.Expr { return call(w.conversionFunc(r.message, "FromProto"), message) }
		toProto := func(m ast.Expr) ast.Expr { return call(w.conversionFunc(r.message, "ToProto"), m) }
		// single runs the call answering one record and answers it.
		single := func(args ...ast.Expr) []ast.Stmt {
			return []ast.Stmt{define([]string{"m", "err"}, run(args...)), failing(), respond(keyValue(responseFields[x], toProto(ident("m"))))}
		}
		// itemsOf encodes the records the variable from holds into items.
		itemsOf := func(from string) []ast.Stmt {
			return []ast.Stmt{
				define([]string{"items"}, makeCall(&ast.ArrayType{Elt: star(w.messageType(r.message))}, lenCall(ident(from)))),
				rangeStmt("i", "m", ident(from), assign(index(ident("items"), ident("i")), toProto(ident("m")))),
			}
		}
		// modelsOf decodes the items of the request into models, each
		// through item; more decodes what else an item carries.
		modelsOf := func(item func(ast.Expr) ast.Expr, more ...ast.Stmt) []ast.Stmt {
			return []ast.Stmt{
				define([]string{"models"}, makeCall(&ast.ArrayType{Elt: star(w.modelPkgType(r.model, r.model.ModelName))}, lenCall(req("items")))),
				rangeStmt("i", "item", req("items"), append([]ast.Stmt{assign(index(ident("models"), ident("i")), fromProto(item(ident("item"))))}, more...)...),
			}
		}
		switch r.action.Phase {
		case consts.PHASE_CREATE:
			body = single(params, fromProto(req(x)))
		case consts.PHASE_GET:
			body = single(params, id, query)
		case consts.PHASE_UPDATE:
			body = single(params, id, fromProto(req(x)))
		case consts.PHASE_PATCH:
			body = single(params, id, fromProto(req(x)), call(sel(req("update_mask"), "GetPaths")))
		case consts.PHASE_DELETE:
			body = []ast.Stmt{ifStmt(define([]string{"err"}, run(params, id)), notNil(ident("err")), returns(ident("nil"), ident("err"))), respond()}
		case consts.PHASE_LIST:
			body = append([]ast.Stmt{define([]string{"models", "total", "err"}, run(params, query)), failing()}, itemsOf("models")...)
			body = append(body, respond(keyValue(responseFields["items"], ident("items")), keyValue(responseFields["total"], call(ident("int64"), ident("total")))))
		case consts.PHASE_CREATE_MANY, consts.PHASE_UPDATE_MANY:
			body = append(modelsOf(func(item ast.Expr) ast.Expr { return item }), define([]string{"stored", "err"}, run(params, ident("models"))), failing())
			body = append(body, itemsOf("stored")...)
			body = append(body, respond(keyValue(responseFields["items"], ident("items"))))
		case consts.PHASE_PATCH_MANY:
			itemFields := goFieldNames(r.request.GetNestedType()[0])
			masks := define([]string{"masks"}, makeCall(&ast.ArrayType{Elt: &ast.ArrayType{Elt: ident("string")}}, lenCall(req("items"))))
			models := modelsOf(func(item ast.Expr) ast.Expr { return call(sel(item, "Get"+itemFields[x])) },
				assign(index(ident("masks"), ident("i")), call(sel(call(sel(ident("item"), "Get"+itemFields["update_mask"])), "GetPaths"))))
			body = append([]ast.Stmt{models[0], masks, models[1]}, define([]string{"stored", "err"}, run(params, ident("models"), ident("masks"))), failing())
			body = append(body, itemsOf("stored")...)
			body = append(body, respond(keyValue(responseFields["items"], ident("items"))))
		case consts.PHASE_DELETE_MANY:
			body = []ast.Stmt{ifStmt(define([]string{"err"}, run(params, req("ids"))), notNil(ident("err")), returns(ident("nil"), ident("err"))), respond()}
		}
	} else {
		var payload ast.Expr
		if r.payload != nil {
			payload = call(w.conversionFunc(r.payload, "FromProto"), req("payload"))
		} else {
			payload = newCall(sel(w.out.imports.fixedRef(ggconst.ImportPathModel), "Empty"))
		}
		if r.result == nil {
			body = []ast.Stmt{ifStmt(define([]string{"_", "err"}, run(params, query, payload)), notNil(ident("err")), returns(ident("nil"), ident("err"))), respond()}
		} else {
			body = []ast.Stmt{
				define([]string{"result", "err"}, run(params, query, payload)),
				failing(),
				respond(keyValue(responseFields["result"], call(w.conversionFunc(r.result, "ToProto"), ident("result")))),
			}
		}
	}

	w.out.add(r.name+" serves the "+r.action.Phase.MethodName()+" action of "+r.model.ModelName+" on "+r.route+".", &ast.FuncDecl{
		Recv: &ast.FieldList{List: []*ast.Field{{Type: ident(r.service)}}},
		Name: ident(r.name),
		Type: &ast.FuncType{
			Params: &ast.FieldList{List: []*ast.Field{
				{Names: []*ast.Ident{ident("ctx")}, Type: sel(w.out.imports.fixedRef(importPathContext), "Context")},
				{Names: []*ast.Ident{ident("req")}, Type: star(ident(r.request.GetName()))},
			}},
			Results: &ast.FieldList{List: []*ast.Field{{Type: star(ident(r.response.GetName()))}, {Type: ident("error")}}},
		},
		Body: block(body...),
	}, layout)
}

// query builds the Query the call of an action of phase takes, read off the
// request through req: the filters, orderings, pagination, cursor and
// expansion of a List, laid out one field per line by the layout returned;
// the expansion of a Get; and the zero Query for any other phase, which
// takes no query.
func (w *fileWriter) query(phase consts.Phase, req func(string) ast.Expr) (ast.Expr, func(*goast.LineSet)) {
	lit := compositeLit(w.grpc("Query"))
	switch phase {
	case consts.PHASE_LIST:
		lit.Elts = []ast.Expr{
			keyValue("Filters", call(w.grpc("Filters"), req("filters"))),
			keyValue("SortBy", req("sort_by")),
			keyValue("Page", req("page")),
			keyValue("Size", req("size")),
			keyValue("CursorField", req("cursor_field")),
			keyValue("CursorValue", req("cursor_value")),
			keyValue("CursorNext", req("cursor_next")),
			keyValue("Expand", req("expand")),
			keyValue("Depth", req("depth")),
		}
		return lit, func(lines *goast.LineSet) { layoutLiteral(lit, lines) }
	case consts.PHASE_GET:
		lit.Elts = []ast.Expr{keyValue("Expand", req("expand")), keyValue("Depth", req("depth"))}
	}
	return lit, nil
}
