// TestRenderColumnsFileWritesATypedReferencePerColumn holds the whole file
// renderColumnsFile writes for one model: it is the example of its doc
// comment, and its columns are the examples of the doc comments of
// columnsImportSpec, columnRefType and columnRefLiteral.
func TestRenderColumnsFileWritesATypedReferencePerColumn(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgPath: "tmpapp/model/sample",
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "Amount", DBName: "amount", TypeExpr: "int64", TypeName: "int64", Numeric: true},
			{GoName: "CreatedAt", DBName: "created_at", TypeExpr: "time.Time", TypeImports: map[string]string{"time": "time"}, TypeName: "time.Time", Time: true},
			{GoName: "Elapsed", DBName: "elapsed", TypeExpr: "time.Duration", TypeImports: map[string]string{"time": "time"}, TypeName: "time.Duration", Numeric: true},
			{GoName: "ID", DBName: "id", TypeExpr: "uuid.UUID", TypeImports: map[string]string{"github.com/gofrs/uuid/v5": "uuid"}, TypeName: "uuid.UUID"},
			{GoName: "Tags", DBName: "tags", TypeName: "datatypes.JSONSlice[string]", JSONStrings: true},
			{GoName: "Weights", DBName: "weights", TypeName: "datatypes.JSONSlice[float64]"},
		},
	}}

	rendered, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)

	require.NoError(t, err)
	require.Equal(t, `// Code generated by gst; DO NOT EDIT.
// source: model/sample/record.go

package sample

import (
	"time"

	uuid "github.com/gofrs/uuid/v5"
	"github.com/hydroan/gst"
)

// RecordCols are the typed column references of Record.
var RecordCols = struct {
	Amount    gst.NumericColumn[int64]
	CreatedAt gst.TimeColumn
	Elapsed   gst.NumericColumn[time.Duration]
	ID        gst.Column[uuid.UUID]
	Tags      gst.JSONStringsColumn
	Weights   gst.Column[any] // datatypes.JSONSlice[float64]
}{
	Amount:    gst.NewNumericColumn[*Record, int64]("amount"),
	CreatedAt: gst.NewTimeColumn[*Record]("created_at"),
	Elapsed:   gst.NewNumericColumn[*Record, time.Duration]("elapsed"),
	ID:        gst.NewColumn[*Record, uuid.UUID]("id"),
	Tags:      gst.NewJSONStringsColumn[*Record]("tags"),
	Weights:   gst.NewColumn[*Record, any]("weights"),
}
`, rendered)
}

// TestRenderColumnsFileWritesAnAnonymousStructType pins that a column
// whose type is an anonymous struct, as a serialized column's is, gets the
// struct written out as its type argument.
func TestRenderColumnsFileWritesAnAnonymousStructType(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgPath: "tmpapp/model/sample",
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "Meta", DBName: "meta", TypeExpr: `struct { A int "json:\"a\"" }`, TypeName: `struct { A int "json:\"a\"" }`},
		},
	}}

	rendered, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)

	require.NoError(t, err)
	require.Contains(t, rendered, "\tMeta gst.Column[struct {\n\t\tA int \"json:\\\"a\\\"\"\n\t}]\n")
	require.Contains(t, rendered, "\tMeta: gst.NewColumn[*Record, struct {\n\t\tA int \"json:\\\"a\\\"\"\n\t}](\"meta\"),\n")
}

func TestRenderColumnsFile(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgPath: "tmpapp/model/sample",
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "Amount", DBName: "amount", TypeExpr: "int64", TypeName: "int64", Numeric: true},
			{GoName: "CreatedAt", DBName: "created_at", TypeExpr: "time.Time", TypeImports: map[string]string{"time": "time"}, TypeName: "time.Time", Time: true},
			{GoName: "ID", DBName: "id", TypeExpr: "string", TypeName: "string"},
			{GoName: "Score", DBName: "score", TypeExpr: "RecordScore", TypeName: "sample.RecordScore", Numeric: true},
			{GoName: "Status", DBName: "status", TypeExpr: "RecordStatus", TypeName: "sample.RecordStatus"},
			{GoName: "Tags", DBName: "tags", TypeName: "datatypes.JSONSlice[string]", JSONStrings: true},
			{GoName: "Weights", DBName: "weights", TypeName: "datatypes.JSONSlice[float64]"},
			{GoName: "Weight", DBName: "weight", TypeName: "weird.Numeric[int]", Numeric: true},
		},
	}}

	rendered, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)
	require.NoError(t, err)

	t.Run("CarriesGeneratedHeaderAndSource", func(t *testing.T) {
		require.True(t, strings.HasPrefix(rendered, "// Code generated by gst; DO NOT EDIT."))
		require.Contains(t, rendered, "// source: model/sample/record.go")
		require.Contains(t, rendered, "package sample")
	})

	t.Run("DeclaresTypedColumns", func(t *testing.T) {
		require.Contains(t, rendered, `gst.NewColumn[*Record, string]("id")`)
		require.Contains(t, rendered, `gst.NewColumn[*Record, RecordStatus]("status")`)
	})

	t.Run("SpecializesNumericColumns", func(t *testing.T) {
		// SUM and AVG only belong on a numeric column, because a database
		// answers SUM over text with 0 rather than an error. A named numeric
		// type keeps its own name as the type argument.
		require.Contains(t, rendered, `gst.NewNumericColumn[*Record, int64]("amount")`)
		require.Contains(t, rendered, `gst.NewNumericColumn[*Record, RecordScore]("score")`)
	})

	t.Run("SpecializesTimeColumns", func(t *testing.T) {
		require.Contains(t, rendered, `gst.NewTimeColumn[*Record]("created_at")`)
	})

	t.Run("SpecializesJSONStringsColumns", func(t *testing.T) {
		// A JSON array of strings is the one column the membership test is
		// generated for; the reference carries no type argument, so the
		// original type needs no comment.
		require.Contains(t, rendered, `gst.NewJSONStringsColumn[*Record]("tags")`)
		require.NotContains(t, rendered, "datatypes.JSONSlice[string]")
	})

	t.Run("DegradesUnreproducibleTypesToAny", func(t *testing.T) {
		// A generic instantiation cannot be written back as source, so the
		// column keeps its exact name but loses the value type. The original
		// type is recorded in a comment.
		require.Contains(t, rendered, `gst.NewColumn[*Record, any]("weights")`)
		require.Contains(t, rendered, "datatypes.JSONSlice[float64]")
	})

	t.Run("DoesNotSpecializeWhenTypeIsUnreproducible", func(t *testing.T) {
		// Specializing would need the type as a type argument, and any is not
		// the column's type. The plain reference keeps the column usable; a
		// NumericColumn minted by hand can still sum it.
		require.Contains(t, rendered, `gst.NewColumn[*Record, any]("weight")`)
		require.NotContains(t, rendered, "gst.NewNumericColumn[any]")
	})

	t.Run("ImportsOnlyWhatItUses", func(t *testing.T) {
		require.Contains(t, rendered, `"github.com/hydroan/gst"`)
		// The time column renders as gst.NewTimeColumn[*Record], which names no
		// time.Time, so the file references nothing of package time; emitting
		// the import anyway would be an unused import that fails to compile.
		require.NotContains(t, rendered, "\n\t\"time\"\n")
		require.NotContains(t, rendered, "gorm.io/datatypes")
	})

	t.Run("IsDeterministic", func(t *testing.T) {
		again, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)
		require.NoError(t, err)
		require.Equal(t, rendered, again)
	})
}

func TestRenderColumnsFileKeepsImportsUsedByTypeArguments(t *testing.T) {
	// time.Duration is numeric, so its reference keeps the type argument and
	// with it the import; only the TimeColumn specialization drops both.
	models := []modelinspect.ModelColumns{{
		PkgPath: "tmpapp/model/sample",
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "CreatedAt", DBName: "created_at", TypeExpr: "time.Time", TypeImports: map[string]string{"time": "time"}, TypeName: "time.Time", Time: true},
			{GoName: "Elapsed", DBName: "elapsed", TypeExpr: "time.Duration", TypeImports: map[string]string{"time": "time"}, TypeName: "time.Duration", Numeric: true},
		},
	}}

	rendered, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)
	require.NoError(t, err)
	require.Contains(t, rendered, `gst.NewNumericColumn[*Record, time.Duration]("elapsed")`)
	require.Contains(t, rendered, "import (\n\t\"time\"\n", "the standard library import is kept, with the name left to the path")
}

// TestRenderColumnsFileImportsEveryPackageACompositeTypeNames pins a column
// of a composite type naming types of two packages: the reference carries
// the type as the inspection wrote it and the file imports both, the
// project's package in a group of its own before the others, as gopls
// groups them.
func TestRenderColumnsFileImportsEveryPackageACompositeTypeNames(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgPath: "tmpapp/model/sample",
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{{
			GoName: "ByKind", DBName: "by_kind", TypeExpr: "map[shared.Kind][]uuid.UUID", TypeName: "map[shared.Kind][]uuid.UUID",
			TypeImports: map[string]string{"tmpapp/shared": "shared", "github.com/gofrs/uuid/v5": "uuid"},
		}},
	}}

	rendered, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)
	require.NoError(t, err)
	require.Contains(t, rendered, `gst.NewColumn[*Record, map[shared.Kind][]uuid.UUID]("by_kind")`)
	require.Contains(t, rendered, "import (\n\t\"tmpapp/shared\"\n\n\tuuid \"github.com/gofrs/uuid/v5\"\n\t\"github.com/hydroan/gst\"\n)\n")
}

// TestRenderColumnsFileNamesEmbeddedColumnsByPath pins that the reference of
// a column inside a struct embedded by name takes its Go path, dots dropped,
// beside the model's own column of the same field name. Its columns are the
// examples of the doc comment of columnFieldName.
func TestRenderColumnsFileNamesEmbeddedColumnsByPath(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "First.Label", DBName: "first_label", TypeExpr: "string", TypeName: "string"},
			{GoName: "ID", DBName: "id", TypeExpr: "string", TypeName: "string"},
			{GoName: "Label", DBName: "label", TypeExpr: "string", TypeName: "string"},
		},
	}}

	rendered, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)

	require.NoError(t, err)
	require.Contains(t, rendered, "\tFirstLabel gst.Column[string]\n")
	require.Contains(t, rendered, "\tFirstLabel: gst.NewColumn[*Record, string](\"first_label\"),\n")
	require.Contains(t, rendered, "\tID         gst.Column[string]\n")
	require.Contains(t, rendered, "\tLabel      gst.Column[string]\n")
}

// TestRenderColumnsFileRejectsCollidingReferenceNames pins that two columns
// whose references would take one field name fail the run, naming both,
// instead of writing a file that does not compile.
func TestRenderColumnsFileRejectsCollidingReferenceNames(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "First.Label", DBName: "first_label", TypeExpr: "string", TypeName: "string"},
			{GoName: "FirstLabel", DBName: "first_label_copy", TypeExpr: "string", TypeName: "string"},
		},
	}}

	_, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)
	require.ErrorContains(t, err, `model Record columns "first_label" and "first_label_copy" both take the reference name FirstLabel`)
}

func TestRenderColumnsFileRejectsImportAliasCollision(t *testing.T) {
	models := []modelinspect.ModelColumns{{
		PkgName: "sample",
		Name:    "Record",
		Columns: []modelinspect.ColumnInfo{
			{GoName: "Left", DBName: "left", TypeExpr: "shared.Kind", TypeImports: map[string]string{"tmpapp/a/shared": "shared"}},
			{GoName: "Right", DBName: "right", TypeExpr: "shared.Kind", TypeImports: map[string]string{"tmpapp/b/shared": "shared"}},
		},
	}}

	_, err := renderColumnsFile("tmpapp", "sample", "model/sample/record.go", models)
	require.Error(t, err, "two packages cannot share one import alias")
}

// TestColumnsImportSpecNamesThePackageWhereThePathDoesNotTellIt pins the
// example of columnsImportSpec, the time and uuid imports, with a package
// named after the major version its path ends in, which gopls names on save,
// and one that matches its path.
func TestColumnsImportSpecNamesThePackageWhereThePathDoesNotTellIt(t *testing.T) {
	tests := []struct{ name, path, want string }{
		{"time", "time", ""},
		{"uuid", "github.com/gofrs/uuid/v5", "uuid"},
		{"v2", "tmpapp/api/v2", "v2"},
		{"shared", "tmpapp/shared", ""},
	}
	for _, tt := range tests {
		got := ""
		if spec := columnsImportSpec(tt.name, tt.path, token.NoPos); spec.Name != nil {
			got = spec.Name.Name
		}
		require.Equal(t, tt.want, got, "columnsImportSpec(%q, %q)", tt.name, tt.path)
	}
}
