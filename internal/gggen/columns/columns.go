// Package columns generates the typed column references of a project's models,
// so filters name columns through the compiler instead of through string
// literals. Every model file declaring a model with columns gets a generated
// file of the same name declaring a <Model>Cols var per such model:
// model/sample/record.go, declaring Record, gets model/sample/record.gen.go
// with RecordCols, and a model without columns, such as one embedding
// model.Empty, gets no var. The columns come from gorm's own schema parser, run
// inside the project's module against the project's real model types by the
// inspection of package modelinspect.
package columns

import (
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/cockroachdb/errors"
	"github.com/hydroan/gst/internal/ggconst"
	"github.com/hydroan/gst/internal/gghelper"
	"github.com/hydroan/gst/internal/modelinspect"
	"github.com/hydroan/gst/internal/modelsource"
)

// Result lists the column files a Generate run changed on disk.
type Result struct {
	// Created and Updated list the files written, in the order of their
	// paths: the ones that were missing, and the ones whose content changed.
	// A file that is already current is not rewritten.
	Created []string
	Updated []string

	// Removed lists the generated files removed because their source file
	// declares no model with columns any more (see removeOrphanColumnFiles).
	Removed []string
}

// Generate writes one .gen.go file per model source file declaring a model with
// columns, removes the generated files of the sources that no longer declare
// one, and returns the files it wrote and removed. Generated files are
// framework-owned for their whole life cycle: projects never create, edit, or
// clean them up. A model file of the model directory named like one of the
// directory's own generated files is refused before anything is written, see
// registrationFileOwner. The files are rendered before any is written (see
// Files), so models whose files cannot be rendered leave the directory as it
// was. When it fails, the result still lists what it wrote and removed before
// the failure.
func Generate(module string, modelDir string, models []*modelsource.Model, ignore gghelper.ProjectIgnore) (Result, error) {
	var result Result

	resolved, inspected, err := modelinspect.Inspect(module, modelDir, models, ignore, func() (map[string]string, error) {
		// The inspection build compiles the model packages before this run
		// writes their column references, so it stubs out the previous
		// generation and leaves out the handwritten code that reads it.
		return InspectionOverlay(module, modelDir, models, ignore)
	})
	if err != nil || !inspected {
		return result, err
	}
	files, err := Files(module, modelDir, models, resolved)
	if err != nil {
		return result, err
	}

	for _, target := range slices.Sorted(maps.Keys(files)) {
		existed, written, writeErr := writeGeneratedFileIfChanged(target, files[target])
		if writeErr != nil {
			return result, writeErr
		}
		switch {
		case !written:
		case existed:
			result.Updated = append(result.Updated, target)
		default:
			result.Created = append(result.Created, target)
		}
	}

	result.Removed, err = removeOrphanColumnFiles(modelDir, files)
	return result, err
}

// Files renders the column reference files of models, the models a scan of
// modelDir read, from resolved, the columns the inspection resolved for them
// (see modelinspect.Inspect), each under its path: one .gen.go file per
// model source file declaring a model with columns, named after it (see
// columnsFileName, and renderColumnsFile for what the file holds). A model
// file of the model directory named like one of the directory's own
// generated files is refused, see registrationFileOwner. For the model
// Record of model/sample/record.go, resolved with the one column ID of type
// string, it returns, under model/sample/record.gen.go,
//
//	// Code generated by gst; DO NOT EDIT.
//	// source: model/sample/record.go
//
//	package sample
//
//	import (
//		"github.com/hydroan/gst"
//	)
//
//	// RecordCols are the typed column references of Record.
//	var RecordCols = struct {
//		ID gst.Column[string]
//	}{
//		ID: gst.NewColumn[*Record, string]("id"),
//	}
func Files(module string, modelDir string, models []*modelsource.Model, resolved []modelinspect.ModelColumns) (map[string]string, error) {
	// The scan that drives generation already knows which file declares each
	// model, so the resolved columns only need to be matched to it.
	sources := make(map[string]string, len(models))
	for _, m := range models {
		sources[m.ImportPath()+"."+m.ModelName] = m.ModelFilePath
	}

	byFile := groupColumnsByFile(resolved, sources)
	for _, file := range slices.Sorted(maps.Keys(byFile)) {
		if owner := registrationFileOwner(modelDir, columnsFileName(file)); owner != "" {
			return nil, errors.Newf("the model file %s would get its column references at %s, the %s; rename the file", file, columnsFileName(file), owner)
		}
	}

	files := make(map[string]string, len(byFile))
	for _, file := range slices.Sorted(maps.Keys(byFile)) {
		entries := byFile[file]
		sort.Slice(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
		content, err := renderColumnsFile(module, entries[0].PkgName, file, entries)
		if err != nil {
			return nil, err
		}
		files[columnsFileName(file)] = content
	}
	return files, nil
}

// groupColumnsByFile matches resolved models to the source files that declare
// them. A model that resolved no columns is dropped, because an empty Cols
// var would reference nothing; a model without a source file here was
// registered from outside the project's model directory, such as a framework
// module, and has no file to generate alongside.
func groupColumnsByFile(resolved []modelinspect.ModelColumns, sources map[string]string) map[string][]modelinspect.ModelColumns {
	byFile := make(map[string][]modelinspect.ModelColumns)
	for _, m := range resolved {
		if len(m.Columns) == 0 {
			continue
		}
		file, ok := sources[m.PkgPath+"."+m.Name]
		if !ok {
			continue
		}
		byFile[file] = append(byFile[file], m)
	}
	return byFile
}

// columnsFileName returns the generated file that belongs to a model source
// file: model/sample/record.go becomes model/sample/record.gen.go.
func columnsFileName(source string) string {
	return strings.TrimSuffix(source, ggconst.ExtensionGo) + ggconst.SuffixGenGo
}

// writeGeneratedFileIfChanged writes content only when it differs from what is
// on disk, so an unchanged model does not churn file timestamps, and reports
// whether the file existed and whether it wrote.
func writeGeneratedFileIfChanged(path string, content string) (existed, written bool, err error) {
	existing, err := os.ReadFile(path)
	if err == nil && string(existing) == content {
		return true, false, nil
	}
	if err != nil && !os.IsNotExist(err) {
		return false, false, errors.Wrapf(err, "read %s", path)
	}
	existed = err == nil
	if err = os.WriteFile(path, []byte(content), ggconst.FileModeGenerated); err != nil {
		return existed, false, errors.Wrapf(err, "write %s", path)
	}
	return existed, true, nil
}

// removeOrphanColumnFiles deletes the generated column files of dir that wanted
// leaves out: those whose source file no longer declares a model with columns,
// which happens when the source file is deleted or renamed, or when its models
// are deleted, moved to another file, or left without columns. It returns the
// files it deleted. Only files carrying the generated header are removed, so a
// hand-written file is reported instead of destroyed.
func removeOrphanColumnFiles(dir string, wanted map[string]string) ([]string, error) {
	var removed []string
	err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || !isColumnFileCandidate(dir, path) {
			return nil
		}
		if _, keep := wanted[path]; keep {
			return nil
		}
		content, err := os.ReadFile(path) //nolint:gosec // path comes from the model directory walk.
		if err != nil {
			return errors.Wrapf(err, "read %s", path)
		}
		if !strings.HasPrefix(string(content), ggconst.CodeGeneratedComment) {
			return errors.Newf("%s uses the generated file suffix but was not generated by gst; rename it", path)
		}
		// #nosec G122 -- path comes from walking the project's own model
		// directory, and only files carrying the generated header reach here.
		if err = os.Remove(path); err != nil {
			return errors.Wrapf(err, "remove orphan generated file %s", path)
		}
		removed = append(removed, path)
		return nil
	})
	return removed, err
}

// isColumnFileCandidate reports whether path can be a generated column file
// of the model directory modelDir at all: it carries the generated suffix and
// is not one of the directory's own generated files, see
// registrationFileOwner: model/sample/record.gen.go and
// model/sample/model.gen.go can be one, while model/model.gen.go,
// model/apidoc.gen.go and model/sample/record.go cannot.
func isColumnFileCandidate(modelDir, path string) bool {
	return strings.HasSuffix(path, ggconst.SuffixGenGo) && registrationFileOwner(modelDir, path) == ""
}

// registrationFileOwner names the generation step owning path when it is one
// of the generated files of the model directory modelDir itself: the
// "registration file" for model/model.gen.go and the "api doc file" for
// model/apidoc.gen.go; "" for every other path, the same names in a
// subdirectory included, which are column files like any other.
func registrationFileOwner(modelDir, path string) string {
	if filepath.Dir(path) != filepath.Clean(modelDir) {
		return ""
	}
	switch filepath.Base(path) {
	case ggconst.FileModelGen:
		return "registration file"
	case ggconst.FileAPIDocGen:
		return "api doc file"
	}
	return ""
}
