// RegistrationFiles renders the registration files of the project at the module
// path module for models, the models a scan of its model directory read (see
// modelsource.ScanModels), each under the path gg gen writes it to:
// model/model.gen.go registers the models with a table (see BuildModelFile),
// model/apidoc.gen.go the doc comments of the model directory, read through
// ignore (see BuildAPIDocFile), service/service.gen.go the service of every
// action declaring one (see BuildServiceFile), and router/router.gen.go the
// route of every action (see BuildRouterFile). For the model Record of
// model/record.go in the module helloworld, a struct without doc comments that
// declares a table and a Create action with a service of its own,
//
//	func (Record) Design() {
//		dsl.Migrate()
//		dsl.Endpoint("records")
//		dsl.Create(func() {
//			dsl.Service()
//		})
//	}
//
// it returns model/model.gen.go,
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package model
//
//	import "github.com/hydroan/gst/model"
//
//	func init() {
//		model.Register[*Record]()
//	}
//
// model/apidoc.gen.go, which registers nothing while the model directory
// carries no doc comment,
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package model
//
//	func init() {
//	}
//
// service/service.gen.go,
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package service
//
//	import (
//		"helloworld/service/record"
//
//		"github.com/hydroan/gst/service"
//	)
//
//	func init() {
//		service.Register[*record.Creator](service.Create, "/api/records")
//	}
//
// and router/router.gen.go:
//
//	// Code generated by gst; DO NOT EDIT.
//
//	package router
//
//	import (
//		"helloworld/model"
//
//		"github.com/hydroan/gst"
//		"github.com/hydroan/gst/router"
//		"github.com/hydroan/gst/service"
//	)
//
//	func Init() error {
//		router.Register[*model.Record, *model.Record, *model.Record](router.Auth(), "/api/records", &gst.ControllerConfig[*model.Record]{}, service.Create)
//		return nil
//	}
func RegistrationFiles(module string, models []*modelsource.Model, ignore gghelper.ProjectIgnore) (map[string]string, error) {
	// The packages each registration file imports, every import path mapped
	// to the name of the package it declares.
	modelPkgs := make(map[string]string)
	servicePkgs := make(map[string]string)
	routerPkgs := make(map[string]string)
	for _, m := range models {
		// The model registration file belongs to the root model package; a
		// model anywhere else is registered through an import of its package.
		if m.Design.Migrate && !m.InModelRoot(ggconst.DirModel) {
			modelPkgs[m.ImportPath()] = m.ModelPkgName
		}

		m.Design.Range(func(_ string, a *dsl.Action) {
			if a.Service {
				target := modelsource.ServiceTarget(m, a, ggconst.DirModel, ggconst.DirService)
				servicePkgs[target.ImportPath] = target.PackageName
			}
			routerPkgs[m.ImportPath()] = m.ModelPkgName
		})
	}

	// A dsl.PayloadEmpty side is emitted as *model.Empty (or *gstmodel.Empty
	// when a routed business model package is itself named "model"), so the
	// qualifier and the import are decided once per router file.
	gstModelPkg, gstModelNeeded := routerGstModelUse(models)
	routerGstModelPkg := ""
	if gstModelNeeded {
		routerGstModelPkg = gstModelPkg
	}
	// A package whose name another import or a framework import of the same
	// file already takes is imported under an alias, and its registrations
	// refer to it through the alias.
	modelAliases := ResolveImportConflicts(modelPkgs, importNames(modelFileImports)...)
	serviceAliases := ResolveImportConflicts(servicePkgs, importNames(serviceFileImports)...)
	routerAliases := routerFileAliases(routerPkgs, routerGstModelPkg)

	modelStmts := make([]ast.Stmt, 0)
	serviceStmts := make([]ast.Stmt, 0)
	routerStmts := make([]ast.Stmt, 0)
	for _, m := range models {
		if !m.Design.Migrate {
			continue
		}
		// A model in the root model package registers unqualified, as in
		// "Register[*Record]()"; any other is qualified by the name its
		// package is imported under, as in "Register[*sample.Record]()".
		if m.InModelRoot(ggconst.DirModel) {
			modelStmts = append(modelStmts, stmtModelRegister(m.ModelName))
		} else {
			modelStmts = append(modelStmts, stmtModelRegister(importQualifier(modelAliases, m.ImportPath(), m.ModelPkgName)+"."+m.ModelName))
		}
	}
	for _, m := range models {
		m.Design.Range(func(route string, act *dsl.Action) {
			// Both registrations below must carry this exact route string:
			// the service registry keys services by route and phase, so the
			// service side and the router side share one route value.
			route, paramName := modelsource.RouterTargetForAction(route, m.Design, act)

			if act.Service {
				target := modelsource.ServiceTarget(m, act, ggconst.DirModel, ggconst.DirService)
				serviceStmts = append(serviceStmts, stmtServiceRegister(importQualifier(serviceAliases, target.ImportPath, target.PackageName)+"."+act.RoleName(), act.Phase, route))
			}
			base := ggconst.RouterAuth
			if act.Public {
				base = ggconst.RouterPublic
			}
			routerStmts = append(routerStmts, stmtRouterRegister(importQualifier(routerAliases, m.ImportPath(), m.ModelPkgName), m.ModelName, act.Payload, act.Result, gstModelPkg, base, route, paramName, act.Phase.Name()))
		})
	}

	modelCode, err := BuildModelFile(module, ggconst.PkgModel, modelAliases, modelStmts...)
	if err != nil {
		return nil, errors.Wrap(err, "build model/model.gen.go")
	}
	// model/apidoc.gen.go registers struct and field doc comments so the
	// OpenAPI document keeps schema descriptions in binaries deployed without
	// Go source files.
	docEntries, err := modelsource.ExtractAPIDocs(module, ggconst.DirModel, ignore, nil)
	if err != nil {
		return nil, errors.Wrap(err, "extract api docs")
	}
	apidocCode, err := BuildAPIDocFile(module, ggconst.PkgModel, ggconst.ImportPathAPIDoc, docEntries)
	if err != nil {
		return nil, errors.Wrap(err, "build model/apidoc.gen.go")
	}
	serviceCode, err := BuildServiceFile(module, ggconst.PkgService, serviceAliases, serviceStmts...)
	if err != nil {
		return nil, errors.Wrap(err, "build service/service.gen.go")
	}
	routerCode, err := BuildRouterFile(module, ggconst.PkgRouter, routerGstModelPkg, routerAliases, routerStmts...)
	if err != nil {
		return nil, errors.Wrap(err, "build router/router.gen.go")
	}
	return map[string]string{
		filepath.Join(ggconst.DirModel, ggconst.FileModelGen):     modelCode,
		filepath.Join(ggconst.DirModel, ggconst.FileAPIDocGen):    apidocCode,
		filepath.Join(ggconst.DirService, ggconst.FileServiceGen): serviceCode,
		filepath.Join(ggconst.DirRouter, ggconst.FileRouterGen):   routerCode,
	}, nil
}

// importQualifier returns the name a generated file refers to the package at
// importPath by: the alias aliases maps it to, or its package name pkgName
// when it was imported without one.
func importQualifier(aliases map[string]string, importPath, pkgName string) string {
	if alias := aliases[importPath]; alias != "" {
		return alias
	}
	return pkgName
}
