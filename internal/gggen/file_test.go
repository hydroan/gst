func TestBuildMainFile(t *testing.T) {
	tests := []struct {
		name        string
		projectName string
		extraDirs   []string
		want        string
	}{
		{
			// The example of the BuildMainFile doc comment.
			name:        "helloworld",
			projectName: "helloworld",
			want: `// Code generated by gst; DO NOT EDIT.

package main

import (
	_ "helloworld/component"
	_ "helloworld/configx"
	_ "helloworld/cronjob"
	_ "helloworld/leader"
	_ "helloworld/lock"
	_ "helloworld/middleware"
	_ "helloworld/model"
	_ "helloworld/module"
	"helloworld/router"
	_ "helloworld/service"

	"github.com/hydroan/gst/bootstrap"
)

func main() {
	bootstrap.RunOrDie(bootstrap.Bootstrap)
	bootstrap.RunOrDie(router.Init)
	bootstrap.RunOrDie(bootstrap.Run)
}
`,
		},
		{
			// A project serving gRPC has an interceptor package, imported
			// for its init function like the middleware package, in its
			// place among the others.
			name:        "with the interceptor package",
			projectName: "helloworld",
			extraDirs:   []string{"interceptor"},
			want: `// Code generated by gst; DO NOT EDIT.

package main

import (
	_ "helloworld/component"
	_ "helloworld/configx"
	_ "helloworld/cronjob"
	_ "helloworld/interceptor"
	_ "helloworld/leader"
	_ "helloworld/lock"
	_ "helloworld/middleware"
	_ "helloworld/model"
	_ "helloworld/module"
	"helloworld/router"
	_ "helloworld/service"

	"github.com/hydroan/gst/bootstrap"
)

func main() {
	bootstrap.RunOrDie(bootstrap.Bootstrap)
	bootstrap.RunOrDie(router.Init)
	bootstrap.RunOrDie(bootstrap.Run)
}
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := gggen.BuildMainFile(tt.projectName, tt.extraDirs...)
			if err != nil {
				t.Fatalf("BuildMainFile() failed: %v", err)
			}
			if got != tt.want {
				t.Errorf("BuildMainFile() = \n%v,\n want \n%v\n", pretty.Sprintf("% #v", got), pretty.Sprintf("% #v", tt.want))
			}
		})
	}
}

func logPrintlnHelloWorld() ast.Stmt {
	return &ast.ExprStmt{
		X: &ast.CallExpr{
			Fun: &ast.SelectorExpr{
				X:   ast.NewIdent("log"),
				Sel: ast.NewIdent("Println"),
			},
			Args: []ast.Expr{
				&ast.BasicLit{Value: `"hello world"`},
			},
		},
	}
}
