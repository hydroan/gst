func TestBuildModelFile(t *testing.T) {
	tests := []struct {
		name    string
		pkgName string
		aliases map[string]string
		stmts   []ast.Stmt
		want    string
	}{
		{
			name:    "empty",
			pkgName: "model",
			stmts:   nil,
			want: `// Code generated by gst; DO NOT EDIT.

package model

func init() {
}
`,
		},
		{
			name:    "user",
			pkgName: "model",
			stmts:   []ast.Stmt{gggen.StmtModelRegister("User")},
			want: `// Code generated by gst; DO NOT EDIT.

package model

import "github.com/hydroan/gst/model"

func init() {
	model.Register[*User]()
}
`,
		},
		{
			// The example of the BuildModelFile doc comment.
			name:    "user_box",
			pkgName: "model",
			aliases: map[string]string{"helloworld/model/sample": ""},
			stmts: []ast.Stmt{
				gggen.StmtModelRegister("User"),
				gggen.StmtModelRegister("sample.Box"),
			},
			want: `// Code generated by gst; DO NOT EDIT.

package model

import (
	"helloworld/model/sample"

	"github.com/hydroan/gst/model"
)

func init() {
	model.Register[*User]()
	model.Register[*sample.Box]()
}
`,
		},
		{
			name:    "aliased_import",
			pkgName: "model",
			aliases: map[string]string{"helloworld/model/sample/model": "sample_model"},
			stmts:   []ast.Stmt{gggen.StmtModelRegister("sample_model.Entry")},
			want: `// Code generated by gst; DO NOT EDIT.

package model

import (
	sample_model "helloworld/model/sample/model"

	"github.com/hydroan/gst/model"
)

func init() {
	model.Register[*sample_model.Entry]()
}
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := gggen.BuildModelFile("helloworld", tt.pkgName, tt.aliases, tt.stmts...)
			if err != nil {
				t.Fatalf("BuildModelFile() failed: %v", err)
			}
			if got != tt.want {
				t.Errorf("BuildModelFile() = \n%v\n, want \n%v\n", pretty.Sprintf("% #v", got), pretty.Sprintf("% #v", tt.want))
			}
		})
	}
}

