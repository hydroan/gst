package gggen_test

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/hydroan/gst/internal/ggconfig"
	"github.com/hydroan/gst/internal/ggconst"
	"github.com/hydroan/gst/internal/gggen"
	"github.com/hydroan/gst/internal/gghelper"
	"github.com/hydroan/gst/internal/modelsource"
)

// TestRegistrationFiles pins the four files RegistrationFiles renders for
// the example of its doc comment, each whole and under the path gg gen
// writes it to.
func TestRegistrationFiles(t *testing.T) {
	projectDir := t.TempDir()
	t.Chdir(projectDir)
	if err := os.WriteFile("go.mod", []byte("module helloworld\n\ngo 1.26\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(ggconst.DirModel, 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(ggconst.DirModel, "record.go"), []byte(`package model

import (
	"github.com/hydroan/gst/dsl"
	"github.com/hydroan/gst/model"
)

type Record struct {
	Title string `+"`json:\"title\"`"+`

	model.Base
}

func (Record) Design() {
	dsl.Migrate()
	dsl.Endpoint("records")
	dsl.Create(func() {
		dsl.Service()
	})
}
`), 0o600); err != nil {
		t.Fatal(err)
	}

	ignore := gghelper.NewProjectIgnore()
	cfg, err := ggconfig.Load(".")
	if err != nil {
		t.Fatal(err)
	}
	scanned, err := modelsource.ScanModels("helloworld", ggconst.DirModel, ignore, cfg)
	if err != nil {
		t.Fatal(err)
	}
	got, err := gggen.RegistrationFiles("helloworld", scanned.Models, ignore)
	if err != nil {
		t.Fatal(err)
	}

	want := map[string]string{
		filepath.Join("model", "model.gen.go"): `// Code generated by gst; DO NOT EDIT.

package model

import "github.com/hydroan/gst/model"

func init() {
	model.Register[*Record]()
}
`,
		filepath.Join("model", "apidoc.gen.go"): `// Code generated by gst; DO NOT EDIT.

package model

func init() {
}
`,
		filepath.Join("service", "service.gen.go"): `// Code generated by gst; DO NOT EDIT.

package service

import (
	"helloworld/service/record"

	"github.com/hydroan/gst/service"
)

func init() {
	service.Register[*record.Creator](service.Create, "/api/records")
}
`,
		filepath.Join("router", "router.gen.go"): `// Code generated by gst; DO NOT EDIT.

package router

import (
	"helloworld/model"

	"github.com/hydroan/gst"
	"github.com/hydroan/gst/router"
	"github.com/hydroan/gst/service"
)

func Init() error {
	router.Register[*model.Record, *model.Record, *model.Record](router.Auth(), "/api/records", &gst.ControllerConfig[*model.Record]{Service: true}, service.Create)
	return nil
}
`,
	}
	if len(got) != len(want) {
		t.Fatalf("RegistrationFiles rendered %d files, want %d: %v", len(got), len(want), got)
	}
	for path, content := range want {
		if got[path] != content {
			t.Errorf("%s =\n%s\nwant\n%s", path, got[path], content)
		}
	}
}
